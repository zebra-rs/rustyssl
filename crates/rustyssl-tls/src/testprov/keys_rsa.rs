/// The DER element at the front of `input`: its contents and what follows.
fn tlv(input: &[u8]) -> (&[u8], &[u8]) {
    let first = input[1];
    let (len, start) = if first < 0x80 {
        (usize::from(first), 2)
    } else {
        let n = usize::from(first & 0x7f);
        (
            input[2..2 + n]
                .iter()
                .fold(0usize, |a, &b| (a << 8) | usize::from(b)),
            2 + n,
        )
    };
    (&input[start..start + len], &input[start + len..])
}

/// The RSA key (named for its use in the RFC 8448-shaped tests: a server's RSA key).
pub fn rfc8448_server() -> PrivateKey {
    let (info, _) = tlv(PKCS8);
    let (_, rest) = tlv(info); // version
    let (_, rest) = tlv(rest); // algorithm
    let (octets, _) = tlv(rest);
    let (seq, _) = tlv(octets);
    let (_, mut rest) = tlv(seq); // version
    let mut parts = Vec::new();
    for _ in 0..8 {
        let (v, r) = tlv(rest);
        let v = v.strip_prefix(&[0]).unwrap_or(v);
        parts.push(v);
        rest = r;
    }
    PrivateKey::rsa(
        parts[0], parts[1], parts[2], parts[3], parts[4], parts[5], parts[6], parts[7],
    )
}
