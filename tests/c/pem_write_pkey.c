static void errors(void)
{
    unsigned long e;
    const char *data;
    int flags;

    printf("  errors:");
    while ((e = ERR_get_error_all(NULL, NULL, NULL, &data, &flags)) != 0) {
        printf(" %d/%d", ERR_GET_LIB(e), ERR_GET_REASON(e));
        if ((flags & ERR_TXT_STRING) != 0 && data != NULL && *data != '\0')
            printf(" [%s]", data);
    }
    printf("\n");
}

static unsigned long fnv(const unsigned char *p, size_t n)
{
    unsigned long h = 2166136261UL;
    size_t i;

    for (i = 0; i < n; i++) {
        h ^= p[i];
        h = (h * 16777619UL) & 0xffffffffUL;
    }
    return h;
}

static void show(const char *label, int r, const unsigned char *p, size_t n)
{
    printf("  %s: %d, %zu octets, %08lx", label, r, n, fnv(p, n));
    if (n > 11 && memcmp(p, "-----BEGIN ", 11) == 0) {
        const unsigned char *nl = memchr(p, '\n', n);

        printf(" [%.*s]", nl == NULL ? (int)n : (int)(nl - p), (const char *)p);
    }
    printf("\n");
    if (r <= 0)
        errors();
}

