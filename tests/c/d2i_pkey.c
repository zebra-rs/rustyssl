/* A temporary file holding the octets, rewound. */
static FILE *file_of(const unsigned char *data, size_t len)
{
    FILE *f = tmpfile();

    if (f != NULL) {
        fwrite(data, 1, len, f);
        rewind(f);
    }
    return f;
}

static void streams(OSSL_LIB_CTX *libctx)
{
    EVP_PKEY *k, *k2;
    BIO *b;
    FILE *f;
    BUF_MEM *m = NULL;
    X509_PUBKEY *xpk;
    const unsigned char *p;
    PKCS8_PRIV_KEY_INFO *p8;
    int n;

    printf("# BIOs, files, and library contexts\n");
    b = BIO_new_mem_buf(ec_p8, sizeof(ec_p8));
    k = d2i_PrivateKey_bio(b, NULL);
    BIO_free(b);
    check(k != NULL, "d2i_PrivateKey_bio");
    describe("bio", k);
    f = file_of(ec_p8, sizeof(ec_p8));
    k2 = d2i_PrivateKey_fp(f, NULL);
    fclose(f);
    check(k2 != NULL && EVP_PKEY_eq(k, k2) == 1, "d2i_PrivateKey_fp");
    EVP_PKEY_free(k2);
    f = file_of(ec_p8, sizeof(ec_p8));
    k2 = d2i_PrivateKey_ex_fp(f, NULL, libctx, NULL);
    fclose(f);
    check(k2 != NULL && EVP_PKEY_eq(k, k2) == 1, "d2i_PrivateKey_ex_fp");
    EVP_PKEY_free(k2);
    f = file_of(ec_spki, sizeof(ec_spki));
    k2 = d2i_PUBKEY_fp(f, NULL);
    fclose(f);
    check(k2 != NULL && EVP_PKEY_eq(k, k2) == 1, "d2i_PUBKEY_fp");
    EVP_PKEY_free(k2);
    f = file_of(ec_spki, sizeof(ec_spki));
    k2 = d2i_PUBKEY_ex_fp(f, NULL, libctx, NULL);
    fclose(f);
    check(k2 != NULL && EVP_PKEY_eq(k, k2) == 1, "d2i_PUBKEY_ex_fp");
    EVP_PKEY_free(k2);
    b = BIO_new_mem_buf(ec_spki, sizeof(ec_spki));
    k2 = d2i_PUBKEY_ex_bio(b, NULL, libctx, NULL);
    BIO_free(b);
    check(k2 != NULL && EVP_PKEY_eq(k, k2) == 1, "d2i_PUBKEY_ex_bio");
    EVP_PKEY_free(k2);
    p = ec_p8;
    k2 = d2i_PrivateKey_ex(EVP_PKEY_EC, NULL, &p, sizeof(ec_p8), libctx, NULL);
    check(k2 != NULL && EVP_PKEY_eq(k, k2) == 1, "d2i_PrivateKey_ex");
    EVP_PKEY_free(k2);
    p = ec_p8;
    k2 = d2i_AutoPrivateKey_ex(NULL, &p, sizeof(ec_p8), libctx, "provider=default");
    check(k2 != NULL && EVP_PKEY_eq(k, k2) == 1, "d2i_AutoPrivateKey_ex");
    describe("auto ex", k2);
    EVP_PKEY_free(k2);
    p = ec_p8;
    p8 = d2i_PKCS8_PRIV_KEY_INFO(NULL, &p, sizeof(ec_p8));
    k2 = EVP_PKCS82PKEY_ex(p8, libctx, NULL);
    check(k2 != NULL && EVP_PKEY_eq(k, k2) == 1, "EVP_PKCS82PKEY_ex");
    PKCS8_PRIV_KEY_INFO_free(p8);
    EVP_PKEY_free(k2);
    EVP_PKEY_free(k);
    errors();

    b = BIO_new_mem_buf(ec_spki, sizeof(ec_spki));
    xpk = d2i_X509_PUBKEY_bio(b, NULL);
    BIO_free(b);
    check(xpk != NULL, "d2i_X509_PUBKEY_bio");
    b = BIO_new(BIO_s_mem());
    check(i2d_X509_PUBKEY_bio(b, xpk) == 1, "i2d_X509_PUBKEY_bio");
    n = (int)BIO_get_mem_data(b, (char **)&p);
    check(n == (int)sizeof(ec_spki) && memcmp(p, ec_spki, sizeof(ec_spki)) == 0,
          "which writes the same octets");
    BIO_free(b);
    f = tmpfile();
    check(f != NULL && i2d_X509_PUBKEY_fp(f, xpk) == 1, "i2d_X509_PUBKEY_fp");
    X509_PUBKEY_free(xpk);
    if (f != NULL) {
        rewind(f);
        xpk = d2i_X509_PUBKEY_fp(f, NULL);
        fclose(f);
        check(xpk != NULL && X509_PUBKEY_get0(xpk) != NULL, "d2i_X509_PUBKEY_fp");
        X509_PUBKEY_free(xpk);
    }
    errors();

    b = BIO_new_mem_buf(dhp, sizeof(dhp));
    k = d2i_KeyParams_bio(EVP_PKEY_DH, NULL, b);
    BIO_free(b);
    check(k != NULL, "d2i_KeyParams_bio");
    describe("params bio", k);
    EVP_PKEY_free(k);

    b = BIO_new_mem_buf(rsa_spki, sizeof(rsa_spki));
    n = asn1_d2i_read_bio(b, &m);
    check(n == (int)sizeof(rsa_spki) && m != NULL && memcmp(m->data, rsa_spki, (size_t)n) == 0,
          "asn1_d2i_read_bio");
    BUF_MEM_free(m);
    m = NULL;
    n = asn1_d2i_read_bio(b, &m);
    check(n == -1, "asn1_d2i_read_bio at the end");
    BIO_free(b);
    b = BIO_new_mem_buf(rsa_spki, 10);
    n = asn1_d2i_read_bio(b, &m);
    check(n == -1, "asn1_d2i_read_bio of a truncated element");
    BIO_free(b);
    errors();
}

