static void one_fixture(const struct fixture *f, OSSL_LIB_CTX *libctx)
{
    const unsigned char *p;
    EVP_PKEY *k1, *k2, *k3, *k4, *k5 = NULL, *k6;
    PKCS8_PRIV_KEY_INFO *p8;
    X509_PUBKEY *xpk;
    BIO *b;
    char what[128];

    printf("# %s\n", f->name);
    p = f->p8;
    k1 = d2i_AutoPrivateKey(NULL, &p, f->p8len);
    snprintf(what, sizeof(what), "%s: d2i_AutoPrivateKey of PrivateKeyInfo", f->name);
    check(k1 != NULL && p == f->p8 + f->p8len, what);
    describe("auto", k1);
    errors();

    p = f->p8;
    k2 = d2i_PrivateKey(f->type, &k5, &p, f->p8len);
    snprintf(what, sizeof(what), "%s: d2i_PrivateKey of its type into *a", f->name);
    check(k2 != NULL && k2 == k5, what);
    describe("typed", k2);
    errors();

    p = f->spki;
    k3 = d2i_PUBKEY(NULL, &p, f->spkilen);
    snprintf(what, sizeof(what), "%s: d2i_PUBKEY", f->name);
    check(k3 != NULL && p == f->spki + f->spkilen, what);
    describe("pub", k3);
    printf("  eq %d %d\n", EVP_PKEY_eq(k1, k3), EVP_PKEY_eq(k1, k2));
    errors();
    if (f->sign && k1 != NULL && k3 != NULL)
        sign_verify(k1, k3);

    p = f->p8;
    p8 = d2i_PKCS8_PRIV_KEY_INFO(NULL, &p, f->p8len);
    k4 = EVP_PKCS82PKEY(p8);
    snprintf(what, sizeof(what), "%s: EVP_PKCS82PKEY", f->name);
    check(k4 != NULL && EVP_PKEY_eq(k4, k3) == 1, what);
    describe("pkcs8", k4);
    PKCS8_PRIV_KEY_INFO_free(p8);
    errors();

    p = f->spki;
    xpk = d2i_X509_PUBKEY(NULL, &p, f->spkilen);
    snprintf(what, sizeof(what), "%s: d2i_X509_PUBKEY's key", f->name);
    check(xpk != NULL && EVP_PKEY_eq(X509_PUBKEY_get0(xpk), k3) == 1, what);
    X509_PUBKEY_free(xpk);
    errors();

    b = BIO_new_mem_buf(f->p8, (int)f->p8len);
    k6 = d2i_PrivateKey_ex_bio(b, NULL, libctx, NULL);
    BIO_free(b);
    snprintf(what, sizeof(what), "%s: d2i_PrivateKey_ex_bio in a library context", f->name);
    check(k6 != NULL && EVP_PKEY_eq(k6, k3) == 1, what);
    describe("libctx", k6);
    EVP_PKEY_free(k6);
    b = BIO_new_mem_buf(f->spki, (int)f->spkilen);
    k6 = d2i_PUBKEY_bio(b, NULL);
    BIO_free(b);
    check(k6 != NULL && EVP_PKEY_eq(k6, k1) == 1, "d2i_PUBKEY_bio");
    EVP_PKEY_free(k6);
    p = f->spki;
    k6 = d2i_PUBKEY_ex(NULL, &p, f->spkilen, libctx, "provider=default");
    check(k6 != NULL, "d2i_PUBKEY_ex with properties");
    describe("pub ex", k6);
    EVP_PKEY_free(k6);
    errors();

    EVP_PKEY_free(k1);
    EVP_PKEY_free(k2);
    EVP_PKEY_free(k3);
    EVP_PKEY_free(k4);
}

