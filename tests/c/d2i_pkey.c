static void errors(void)
{
    unsigned long e;
    const char *data;
    int flags;

    printf("  errors:");
    while ((e = ERR_get_error_all(NULL, NULL, NULL, &data, &flags)) != 0) {
        printf(" %d/%d", ERR_GET_LIB(e), ERR_GET_REASON(e));
        if ((flags & ERR_TXT_STRING) != 0 && data != NULL && *data != '\0')
            printf(" [%s]", data);
    }
    printf("\n");
}

static void hex(const unsigned char *p, size_t n)
{
    size_t i;

    for (i = 0; i < n && i < 12; i++)
        printf("%02x", p[i]);
    if (n > 12)
        printf("..(%zu)", n);
}

/* What a key is, without printing it (printing provided keys needs encoders). */
static void describe(const char *label, EVP_PKEY *pk)
{
    const OSSL_PROVIDER *prov;
    unsigned char buf[1024];
    size_t len = 0;
    BIGNUM *bn = NULL;

    printf("  %s:", label);
    if (pk == NULL) {
        printf(" NULL\n");
        return;
    }
    prov = EVP_PKEY_get0_provider(pk);
    printf(" id %d base %d type %s bits %d sec %d size %d prov %s",
           EVP_PKEY_get_id(pk), EVP_PKEY_get_base_id(pk),
           EVP_PKEY_get0_type_name(pk) != NULL ? EVP_PKEY_get0_type_name(pk) : "-",
           EVP_PKEY_get_bits(pk), EVP_PKEY_get_security_bits(pk), EVP_PKEY_get_size(pk),
           prov != NULL ? OSSL_PROVIDER_get0_name(prov) : "legacy");
    if (EVP_PKEY_get_octet_string_param(pk, OSSL_PKEY_PARAM_ENCODED_PUBLIC_KEY, buf,
                                        sizeof(buf), &len)) {
        printf(" enc ");
        hex(buf, len);
    } else if (EVP_PKEY_get_bn_param(pk, OSSL_PKEY_PARAM_RSA_N, &bn)
               || EVP_PKEY_get_bn_param(pk, OSSL_PKEY_PARAM_PUB_KEY, &bn)) {
        printf(" pubbits %d", BN_num_bits(bn));
    }
    BN_free(bn);
    bn = NULL;
    printf(" priv %d",
           EVP_PKEY_get_bn_param(pk, OSSL_PKEY_PARAM_RSA_D, &bn)
           || EVP_PKEY_get_bn_param(pk, OSSL_PKEY_PARAM_PRIV_KEY, &bn)
           || EVP_PKEY_get_octet_string_param(pk, OSSL_PKEY_PARAM_PRIV_KEY, buf, sizeof(buf),
                                              &len));
    BN_free(bn);
    printf("\n");
    ERR_clear_error();
}

/* A signature made with priv verifies with pub (for the signing types). */
static void sign_verify(EVP_PKEY *priv, EVP_PKEY *pub)
{
    static const unsigned char msg[] = "the message";
    unsigned char sig[1024];
    size_t siglen = sizeof(sig);
    EVP_MD_CTX *ctx = EVP_MD_CTX_new();
    int ed = EVP_PKEY_is_a(priv, "ED25519") || EVP_PKEY_is_a(priv, "ED448");
    int ok;

    ok = EVP_DigestSignInit(ctx, NULL, ed ? NULL : EVP_sha256(), NULL, priv) == 1
         && EVP_DigestSign(ctx, sig, &siglen, msg, sizeof(msg)) == 1;
    EVP_MD_CTX_free(ctx);
    ctx = EVP_MD_CTX_new();
    ok = ok && EVP_DigestVerifyInit(ctx, NULL, ed ? NULL : EVP_sha256(), NULL, pub) == 1
         && EVP_DigestVerify(ctx, sig, siglen, msg, sizeof(msg)) == 1;
    EVP_MD_CTX_free(ctx);
    printf("  sign/verify %d\n", ok);
    ERR_clear_error();
}

