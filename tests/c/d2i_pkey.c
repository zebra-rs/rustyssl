static void to_pkcs8(const char *label, EVP_PKEY *pk, const unsigned char *want, size_t wantlen)
{
    PKCS8_PRIV_KEY_INFO *p8 = EVP_PKEY2PKCS8(pk);
    unsigned char *der = NULL;
    int n = p8 != NULL ? i2d_PKCS8_PRIV_KEY_INFO(p8, &der) : -1;

    printf("  %s: len %d same %d\n", label, n,
           n > 0 && (size_t)n == wantlen && memcmp(der, want, wantlen) == 0);
    OPENSSL_free(der);
    PKCS8_PRIV_KEY_INFO_free(p8);
    errors();
}

