    write_file("hashed/other.pem", RSA_PEM, strlen(RSA_PEM));
    write_file("hashed/.hidden", RSA_PEM, strlen(RSA_PEM));

    ctx = OSSL_STORE_open(sub, NULL, NULL, NULL, NULL);
    check(ctx != NULL, "opened");
    while ((info = OSSL_STORE_load(ctx)) != NULL) {
        n++;
        OSSL_STORE_INFO_free(info);
    }
    printf("  %d names, eof %d\n", n, OSSL_STORE_eof(ctx));
    OSSL_STORE_close(ctx);

    s = OSSL_STORE_SEARCH_by_name(X509_get_subject_name(ca));
    ctx = OSSL_STORE_open(sub, NULL, NULL, NULL, NULL);
    printf("  supports by name %d\n", OSSL_STORE_supports_search(ctx, OSSL_STORE_SEARCH_BY_NAME));
    check(OSSL_STORE_find(ctx, s) == 1, "OSSL_STORE_find by name");
    printf("  %d\n", drain(ctx));
