static char *path_of(const char *name)
{
    static char paths[16][128];
    static int k;
    char *p = paths[k++ % 16];

    snprintf(p, 128, "%s/%s", dir, name);
    return p;
}

static void write_file(const char *name, const void *data, size_t len)
{
    FILE *f = fopen(path_of(name), "wb");

    if (f != NULL) {
        fwrite(data, 1, len, f);
        fclose(f);
    }
}

static X509 *cert(const char *pem)
{
    BIO *b = BIO_new_mem_buf(pem, -1);
    X509 *x = PEM_read_bio_X509(b, NULL, NULL, NULL);

    BIO_free(b);
    return x;
}

/* What an information holds, shown. */
static void show_info(OSSL_STORE_INFO *info)
{
    int t = OSSL_STORE_INFO_get_type(info);
    const char *ts = OSSL_STORE_INFO_type_string(t);

    printf("  %s:", ts != NULL ? ts : "(null)");
    switch (t) {
    case OSSL_STORE_INFO_NAME: {
        const char *n = OSSL_STORE_INFO_get0_NAME(info);
        const char *d = OSSL_STORE_INFO_get0_NAME_description(info);

        printf(" ");
        show(n);
        printf(" (%s)", d != NULL ? d : "no description");
        break;
    }
    case OSSL_STORE_INFO_CERT:
        printf(" ");
        X509_NAME_print_ex_fp(stdout, X509_get_subject_name(OSSL_STORE_INFO_get0_CERT(info)), 0, XN_FLAG_ONELINE);
        break;
    case OSSL_STORE_INFO_CRL:
        printf(" ");
        X509_NAME_print_ex_fp(stdout, X509_CRL_get_issuer(OSSL_STORE_INFO_get0_CRL(info)), 0, XN_FLAG_ONELINE);
        break;
    case OSSL_STORE_INFO_PKEY:
    case OSSL_STORE_INFO_PUBKEY:
    case OSSL_STORE_INFO_PARAMS: {
        EVP_PKEY *k = OSSL_STORE_INFO_get0_data(t, info);

        printf(" %s, %d bits", EVP_PKEY_get0_type_name(k), EVP_PKEY_get_bits(k));
        break;
    }
    }
    printf("\n");
}

/* Every object of an open store, shown, then the store closed. */
static int drain(OSSL_STORE_CTX *ctx)
{
    int n = 0;
    OSSL_STORE_INFO *info;

    while ((info = OSSL_STORE_load(ctx)) != NULL) {
        show_info(info);
        OSSL_STORE_INFO_free(info);
        n++;
    }
    printf("  eof %d, error %d\n", OSSL_STORE_eof(ctx), OSSL_STORE_error(ctx));
    errors();
    printf("  close %d\n", OSSL_STORE_close(ctx));
    return n;
}

static int read_all(const char *label, const char *uri, UI_METHOD *ui)
{
    OSSL_STORE_CTX *ctx;

    printf("# %s\n", label);
    ctx = OSSL_STORE_open(uri, ui, NULL, NULL, NULL);
    if (ctx == NULL) {
        printf("  not opened\n");
        errors();
        return -1;
    }
    return drain(ctx);
}

