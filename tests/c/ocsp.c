static BIO *mem(const char *s)
{
    return BIO_new_mem_buf(s, -1);
}

static X509 *cert(const char *pem)
{
    BIO *b = mem(pem);
    X509 *x = PEM_read_bio_X509(b, NULL, NULL, NULL);

    BIO_free(b);
    return x;
}

static EVP_PKEY *key(const char *pem)
{
    BIO *b = mem(pem);
    EVP_PKEY *k = PEM_read_bio_PrivateKey(b, NULL, NULL, NULL);

    BIO_free(b);
    return k;
}

static OCSP_RESPONSE *load_resp(const unsigned char *der, long len)
{
    const unsigned char *p = der;

    return d2i_OCSP_RESPONSE(NULL, &p, len);
}

static OCSP_REQUEST *load_req(const unsigned char *der, long len)
{
    const unsigned char *p = der;

    return d2i_OCSP_REQUEST(NULL, &p, len);
}

static const char *oid(const ASN1_OBJECT *o)
{
    static char bufs[4][80];
    static int k;
    char *buf = bufs[k++ % 4];

    if (o == NULL)
        return "(none)";
    OBJ_obj2txt(buf, 80, o, 0);
    return buf;
}

static void hex(const char *label, const unsigned char *p, int n)
{
    int i;

    printf("  %s (%d):", label, n);
    for (i = 0; i < n; i++)
        printf("%s%02x", i % 32 == 0 ? "\n    " : "", p[i]);
    printf("\n");
}

static void fingerprint(const char *label, const unsigned char *d, int n)
{
    unsigned char md[32];
    unsigned int mdlen = 0;

    EVP_Digest(d, (size_t)n, md, &mdlen, EVP_sha256(), NULL);
    printf("  %s: DER %d,", label, n);
    hex("sha256", md, (int)mdlen);
}

