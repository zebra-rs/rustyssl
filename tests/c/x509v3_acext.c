/*
 * Conformance test for the attribute certificate extensions: time specifications
 * (OSSL_TIME_SPEC_new(3) and its parts), targeting information, the authority attribute
 * identifier, basic attribute constraints, issued on behalf of, role specification
 * certificate identifiers, subject directory attributes and associated information, user
 * notices, attribute descriptors, attribute mappings, allowed attribute assignments, the AA
 * issuing distribution point, the NULL markers, and X509_signature_dump, in TAP format: each
 * type made empty, encoded, and decoded; each extension decoded from DER and printed at two
 * indents; the ones with a configuration form made from text.
 *
 * Built once against the vendored headers, then run against the reference OpenSSL and against
 * rustyssl: it must pass on both with the same output (TEST_PLAN.md, layer L4).
 */
