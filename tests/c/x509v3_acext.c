static void test_config(void)
{
    BIO *b = BIO_new_mem_buf(config, -1);
    CONF *conf = NCONF_new(NULL);
    long eline = 0;
    static const int markers[] = {
        NID_indirect_issuer, NID_no_assertion, NID_soa_identifier,
        NID_group_ac, NID_no_rev_avail, NID_single_use,
    };
    size_t i;

    check(NCONF_load_bio(conf, b, &eline) == 1, "loaded the configuration");
    made("basic attribute constraints", conf, NID_basic_att_constraints, "authority:TRUE,pathlen:2");
    made("basic attribute constraints", conf, NID_basic_att_constraints, "authority:no");
    made("basic attribute constraints", conf, NID_basic_att_constraints, "pathlen:x");
    made("basic attribute constraints", conf, NID_basic_att_constraints, "other:1");
    for (i = 0; i < sizeof(markers) / sizeof(markers[0]); i++)
        made(OBJ_nid2sn(markers[i]), conf, markers[i], "anything");
    made("AA issuing distribution point", conf, NID_id_aa_issuing_distribution_point, "URI:http://aa.example/");
    made("AA issuing distribution point", conf, NID_id_aa_issuing_distribution_point, "aadp");
    made("AA issuing distribution point", conf, NID_id_aa_issuing_distribution_point, "aadp_rel");
    made("AA issuing distribution point", conf, NID_id_aa_issuing_distribution_point, "aadp_bad");
    made("AA issuing distribution point", conf, NID_id_aa_issuing_distribution_point, "nosection");
    made("AA issuing distribution point", conf, NID_id_aa_issuing_distribution_point, "bad:name");
    made("targeting information", conf, NID_target_information, "x");
    made("time specification", conf, NID_time_specification, "x");
    NCONF_free(conf);
    BIO_free(b);
}

static void test_signature_dump(void)
{
    unsigned char data[40];
    ASN1_STRING *s = ASN1_STRING_new();
    int i;

    for (i = 0; i < 40; i++)
        data[i] = (unsigned char)(i * 7);
    printf("# X509_signature_dump\n");
    ASN1_STRING_set(s, data, 40);
    printf("  40: %d\n", X509_signature_dump(out, s, 4));
    print_out("dump");
    ASN1_STRING_set(s, data, 18);
    printf("  18: %d\n", X509_signature_dump(out, s, 0));
    print_out("dump");
    ASN1_STRING_set(s, data, 0);
    printf("  0: %d\n", X509_signature_dump(out, s, 2));
    print_out("dump");
    errors();
    ASN1_STRING_free(s);
}

