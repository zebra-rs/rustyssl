static int failures = 0;
static int number = 0;

static void check(int ok, const char *what)
{
    number++;
    if (!ok)
        failures++;
    printf("%s %d - %s\n", ok ? "ok" : "not ok", number, what);
}

static void errors(void)
{
    unsigned long e;
    const char *data;
    int flags;

    printf("  errors:");
    while ((e = ERR_get_error_all(NULL, NULL, NULL, &data, &flags)) != 0) {
        printf(" %d/%d", ERR_GET_LIB(e), ERR_GET_REASON(e));
        if ((flags & ERR_TXT_STRING) != 0 && data != NULL && *data != '\0')
            printf(" [%s]", data);
    }
    printf("\n");
}

static void hex(const char *label, const unsigned char *p, long n)
{
    long i;

    printf("  %s (%ld):", label, n);
    for (i = 0; i < n; i++)
        printf("%s%02x", i % 32 == 0 && i > 0 ? "\n    " : " ", p[i]);
    printf("\n");
}

static BIO *out;

static void print_out(const char *label)
{
    char *data;
    long n = BIO_get_mem_data(out, &data);

    printf("  %s: [", label);
    fwrite(data, 1, (size_t)n, stdout);
    printf("]\n");
    (void)BIO_reset(out);
}

/* A type made empty, encoded, and decoded again; its item's name. */
#define EMPTY(T, NEW, FREE, I2D, D2I, IT)                                         \
    do {                                                                          \
        T *v = NEW();                                                             \
        unsigned char *der = NULL;                                                \
        int n = v == NULL ? -2 : I2D(v, &der);                                    \
        const unsigned char *q = der;                                             \
        T *w = n > 0 ? D2I(NULL, &q, n) : NULL;                                   \
                                                                                  \
        printf("# empty %s, item %s\n", #T, IT()->sname);                         \
        check(v != NULL, "made");                                                 \
        printf("  encoded: %d\n", n);                                             \
        if (n > 0)                                                                \
            hex("der", der, n);                                                   \
        printf("  decoded: %s\n", w != NULL ? "yes" : "no");                      \
        errors();                                                                 \
        OPENSSL_free(der);                                                        \
        FREE(w);                                                                  \
        FREE(v);                                                                  \
        FREE(NULL);                                                               \
    } while (0)

/* DER of a type decoded and encoded again (a DEFAULT value given changes it). */
#define ROUND(T, FREE, I2D, D2I, DER)                                             \
    do {                                                                          \
        const unsigned char *q = DER;                                             \
        T *v = D2I(NULL, &q, (long)sizeof(DER));                                  \
        unsigned char *der = NULL;                                                \
        int n = v == NULL ? -2 : I2D(v, &der);                                    \
                                                                                  \
        check(v != NULL && q == DER + sizeof(DER), "decoded " #DER);              \
        printf("  encoded again: %s\n",                                          \
               n == (int)sizeof(DER) && memcmp(der, DER, sizeof(DER)) == 0        \
                   ? "the same" : "differently");                                 \
        errors();                                                                 \
        OPENSSL_free(der);                                                        \
        FREE(v);                                                                  \
    } while (0)

/* An extension of `nid` decoded from DER, and printed at indents 0 and 4. */
static void decoded(const char *label, int nid, const unsigned char *der, int len)
{
    ASN1_OCTET_STRING *oct = ASN1_OCTET_STRING_new();
    X509_EXTENSION *e;
    void *v;

    ASN1_OCTET_STRING_set(oct, der, len);
    e = X509_EXTENSION_create_by_NID(NULL, nid, 0, oct);
    printf("# %s\n", label);
    v = X509V3_EXT_d2i(e);
    check(v != NULL, "decoded");
    errors();
    if (v != NULL)
        ASN1_item_free(v, ASN1_ITEM_ptr(X509V3_EXT_get_nid(nid)->it));
    printf("  print 0: %d\n", X509V3_EXT_print(out, e, 0, 0));
    print_out("printed");
    errors();
    printf("  print 4: %d\n", X509V3_EXT_print(out, e, X509V3_EXT_MULTILINE, 4));
    print_out("printed");
    errors();
    X509_EXTENSION_free(e);
    ASN1_OCTET_STRING_free(oct);
}

#define DECODED(nid, der) decoded(#der, nid, der, (int)sizeof(der))

static void show_ext(const char *label, X509_EXTENSION *e)
{
    unsigned char *der = NULL;
    int len;

    if (e == NULL) {
        printf("  %s: none\n", label);
        errors();
        return;
    }
    len = i2d_X509_EXTENSION(e, &der);
    hex(label, der, len);
    OPENSSL_free(der);
    printf("  print: %d\n", X509V3_EXT_print(out, e, 0, 2));
    print_out("printed");
    errors();
}

/* An extension made from configuration text (`X509V3_EXT_nconf_nid`). */
static void made(const char *label, CONF *conf, int nid, const char *text)
{
    X509V3_CTX ctx;
    X509_EXTENSION *e;

    X509V3_set_ctx(&ctx, NULL, NULL, NULL, NULL, 0);
    X509V3_set_nconf(&ctx, conf);
    e = X509V3_EXT_nconf_nid(conf, &ctx, nid, text);
    printf("# %s: %s\n", label, text);
    show_ext("extension", e);
    X509_EXTENSION_free(e);
}

