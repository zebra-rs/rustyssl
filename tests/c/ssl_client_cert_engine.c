static X509 *cert(const char *pem)
{
    BIO *b = BIO_new_mem_buf(pem, -1);
    X509 *x = PEM_read_bio_X509(b, NULL, NULL, NULL);

    BIO_free(b);
    return x;
}

static EVP_PKEY *key(const char *pem)
{
    BIO *b = BIO_new_mem_buf(pem, -1);
    EVP_PKEY *k = PEM_read_bio_PrivateKey(b, NULL, NULL, NULL);

    BIO_free(b);
    return k;
}

/* A server context with the server's certificate and key. */
static SSL_CTX *server_ctx(void)
{
    SSL_CTX *ctx = SSL_CTX_new(TLS_server_method());
    X509 *x = cert(SERVER_PEM);
    EVP_PKEY *k = key(SERVER_KEY_PEM);

    if (ctx == NULL || x == NULL || k == NULL || SSL_CTX_use_certificate(ctx, x) != 1
        || SSL_CTX_use_PrivateKey(ctx, k) != 1) {
        printf("Bail out! server context\n");
        exit(1);
    }
    X509_free(x);
    EVP_PKEY_free(k);
    return ctx;
}

/* A client context that trusts the test root and checks the server's certificate. */
static SSL_CTX *client_ctx(void)
{
    SSL_CTX *ctx = SSL_CTX_new(TLS_client_method());
    X509 *ca = cert(CA_PEM);

    if (ctx == NULL || ca == NULL || X509_STORE_add_cert(SSL_CTX_get_cert_store(ctx), ca) != 1) {
        printf("Bail out! client context\n");
        exit(1);
    }
    X509_free(ca);
    SSL_CTX_set_verify(ctx, SSL_VERIFY_PEER, NULL);
    return ctx;
}

/* Connects a client and a server over an in-memory BIO pair. */
static void pair(SSL *c, SSL *s)
{
    BIO *a = NULL, *b = NULL;

    if (BIO_new_bio_pair(&a, 0, &b, 0) != 1) {
        printf("Bail out! BIO pair\n");
        exit(1);
    }
    SSL_set_bio(c, a, a);
    SSL_set_bio(s, b, b);
    SSL_set_connect_state(c);
    SSL_set_accept_state(s);
}

/*
 * Runs both ends' handshakes in turn until both finish (0), or one stops for something other
 * than I/O (its SSL_get_error value, after printing which end). Each end's wants are printed
 * when `trace` is set.
 */
static int run(SSL *c, SSL *s, int trace)
{
    int cdone = SSL_is_init_finished(c), sdone = SSL_is_init_finished(s), round;

    for (round = 0; round < 64 && (!cdone || !sdone); round++) {
        int i;

        for (i = 0; i < 2; i++) {
            SSL *x = i == 0 ? c : s;
            int *done = i == 0 ? &cdone : &sdone, r, e;

            if (*done)
                continue;
            r = SSL_do_handshake(x);
            if (r == 1) {
                *done = 1;
                if (trace)
                    printf("  %s: done\n", i == 0 ? "client" : "server");
                continue;
            }
            e = SSL_get_error(x, r);
            if (trace)
                printf("  %s: %d -> %d\n", i == 0 ? "client" : "server", r, e);
            if (e != SSL_ERROR_WANT_READ && e != SSL_ERROR_WANT_WRITE) {
                printf("  %s stopped: %d\n", i == 0 ? "client" : "server", e);
                return e;
            }
        }
    }
    return cdone && sdone ? 0 : -1;
}

/* A connected client and server from the two contexts. */
static void connect_pair(SSL_CTX *cctx, SSL_CTX *sctx, SSL **c, SSL **s)
{
    *c = SSL_new(cctx);
    *s = SSL_new(sctx);
    if (*c == NULL || *s == NULL) {
        printf("Bail out! SSL_new\n");
        exit(1);
    }
    pair(*c, *s);
}

/*
 * The client certificate engine: what it's asked, what it returns, and the callback after it.
 */
static int engine_loads, engine_result, cb_calls, ca_count;

static int engine_client_cert(ENGINE *e, SSL *s, STACK_OF(X509_NAME) *ca, X509 **x,
                              EVP_PKEY **k, STACK_OF(X509) **other, UI_METHOD *ui, void *data)
{
    (void)e;
    (void)s;
    (void)other;
    (void)ui;
    (void)data;
    engine_loads++;
    ca_count = sk_X509_NAME_num(ca);
    if (engine_result == 1) {
        *x = cert(SERVER_PEM);
        *k = key(SERVER_KEY_PEM);
    }
    return engine_result;
}

static int client_cert_cb(SSL *s, X509 **x, EVP_PKEY **k)
{
    (void)s;
    cb_calls++;
    *x = cert(SERVER_PEM);
    *k = key(SERVER_KEY_PEM);
    return 1;
}

static int accept_any(int ok, X509_STORE_CTX *store)
{
    (void)ok;
    (void)store;
    return 1;
}

static int finishes;

static int engine_finish(ENGINE *e)
{
    (void)e;
    finishes++;
    return 1;
}

static void handshake(ENGINE *e, int max, int result, int with_cb)
{
    SSL_CTX *cctx = client_ctx(), *sctx = server_ctx();
    SSL *c, *s;
    int r;

    SSL_CTX_set_max_proto_version(cctx, max);
    SSL_CTX_set_verify(sctx, SSL_VERIFY_PEER, accept_any);
    check(SSL_CTX_set_client_cert_engine(cctx, e) == 1, "SSL_CTX_set_client_cert_engine");
    if (with_cb)
        SSL_CTX_set_client_cert_cb(cctx, client_cert_cb);
    engine_result = result;
    engine_loads = cb_calls = 0;
    ca_count = -2;
    connect_pair(cctx, sctx, &c, &s);
    r = run(c, s, 0);
    printf("  %s, engine returns %d%s: handshake %d, engine loads %d (CA names %d), "
           "callback calls %d, client certificate %s\n",
           max == TLS1_2_VERSION ? "TLS 1.2" : "TLS 1.3", result, with_cb ? ", callback" : "",
           r, engine_loads, ca_count, cb_calls,
           SSL_get0_peer_certificate(s) != NULL ? "sent" : "none");
    errors();
    SSL_free(c);
    SSL_free(s);
    SSL_CTX_free(cctx);
    SSL_CTX_free(sctx);
}

int main(void)
{
    ENGINE *e = ENGINE_new(), *bare = ENGINE_new();
    SSL_CTX *ctx = SSL_CTX_new(TLS_client_method());

    check(e != NULL && bare != NULL && ctx != NULL, "engines and a context");
    ENGINE_set_id(e, "rustyssl-client-cert");
    ENGINE_set_id(bare, "rustyssl-bare");
    ENGINE_set_load_ssl_client_cert_function(e, engine_client_cert);
    ENGINE_set_finish_function(e, engine_finish);

    ERR_clear_error();
    check(SSL_CTX_set_client_cert_engine(ctx, bare) == 0, "an engine without the function");
    errors();
    check(SSL_CTX_set_client_cert_engine(ctx, NULL) == 0, "no engine");
    errors();
    SSL_CTX_free(ctx);

    handshake(e, TLS1_3_VERSION, 1, 0);
    handshake(e, TLS1_2_VERSION, 1, 0);
    handshake(e, TLS1_3_VERSION, 0, 1);
    handshake(e, TLS1_3_VERSION, 0, 0);
    handshake(e, TLS1_2_VERSION, 1, 1);
    printf("  finishes %d\n", finishes);

    ENGINE_free(bare);
    ENGINE_free(e);
    printf("1..%d\n", number);
    return failures != 0;
}
