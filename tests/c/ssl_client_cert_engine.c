/*
 * Conformance test for SSL_CTX_set_client_cert_engine(3): an engine without a client
 * certificate function (or none) is refused; a client's engine is asked for the certificate
 * before the client certificate callback (SSL_CTX_set_client_cert_cb(3)), which runs only when
 * the engine gives 0; TLS 1.3 and 1.2.
 *
 * Built once against the vendored headers, then run against the reference OpenSSL and against
 * rustyssl: it must pass on both with the same output (TEST_PLAN.md, layer L4).
 */
#define OPENSSL_SUPPRESS_DEPRECATED
