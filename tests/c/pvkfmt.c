static int cb_calls = 0;

static int pw_cb(char *buf, int size, int rwflag, void *u)
{
    const char *pass = u;
    int n = (int)strlen(pass);

    cb_calls++;
    printf("  pw_cb(size %d, rwflag %d)\n", size, rwflag);
    if (n > size)
        return -1;
    memcpy(buf, pass, n);
    return n;
}

static EVP_PKEY *load(const unsigned char *der, long len)
{
    const unsigned char *p = der;

    return d2i_AutoPrivateKey(NULL, &p, len);
}

/* What the BIO holds, as a copy. */
static unsigned char *contents(BIO *b, long *len)
{
    char *data = NULL;
    unsigned char *copy;

    *len = BIO_get_mem_data(b, &data);
    copy = OPENSSL_malloc(*len > 0 ? *len : 1);
    if (*len > 0)
        memcpy(copy, data, *len);
    return copy;
}

/* The key's blob (or PVK, for pvk) written to memory: its octets, or NULL. */
static unsigned char *write_blob(EVP_PKEY *k, int kind, long *len)
{
    BIO *b = BIO_new(BIO_s_mem());
    unsigned char *out;
    int r;

    if (kind == 0)
        r = i2b_PrivateKey_bio(b, k);
    else if (kind == 1)
        r = i2b_PublicKey_bio(b, k);
    else
        r = i2b_PVK_bio(b, k, 0, NULL, NULL);
    printf("  written: %d\n", r);
    out = contents(b, len);
    BIO_free(b);
    if (r <= 0) {
        OPENSSL_free(out);
        return NULL;
    }
    return out;
}

static void show_key(const char *label, EVP_PKEY *k, EVP_PKEY *orig)
{
    if (k == NULL) {
        printf("  %s: NULL\n", label);
        errors();
        return;
    }
    printf("  %s: %s, %d bits, eq %d\n", label, EVP_PKEY_get0_type_name(k), EVP_PKEY_get_bits(k),
           EVP_PKEY_eq(k, orig));
}

static void test_blob(const char *name, EVP_PKEY *k, int ispub)
{
    long len = 0, len2 = 0;
    unsigned char *blob, *again;
    const unsigned char *p;
    EVP_PKEY *got;
    BIO *b;
    char what[128];

    printf("# %s %s blob\n", name, ispub ? "public" : "private");
    blob = write_blob(k, ispub, &len);
    snprintf(what, sizeof(what), "%s %s blob written", name, ispub ? "public" : "private");
    check(blob != NULL, what);
    if (blob == NULL) {
        errors();
        return;
    }
    digest("blob", blob, len);

    p = blob;
    got = ispub ? b2i_PublicKey(&p, len) : b2i_PrivateKey(&p, len);
    show_key("read", got, k);
    printf("  in moved %d\n", (int)(p - blob));
    snprintf(what, sizeof(what), "%s %s blob read back", name, ispub ? "public" : "private");
    check(got != NULL && EVP_PKEY_eq(got, k) == 1, what);
    if (got != NULL) {
        b = BIO_new(BIO_s_mem());
        printf("  rewritten: %d\n", ispub ? i2b_PublicKey_bio(b, got) : i2b_PrivateKey_bio(b, got));
        again = contents(b, &len2);
        check(len2 == len && memcmp(again, blob, len) == 0, "the same blob again");
        OPENSSL_free(again);
        BIO_free(b);
    }
    EVP_PKEY_free(got);

    /* The other kind's reader. */
    p = blob;
    got = ispub ? b2i_PrivateKey(&p, len) : b2i_PublicKey(&p, len);
    show_key("other kind", got, k);
    EVP_PKEY_free(got);

    /* Too short, by one and to less than a header. */
    p = blob;
    got = ispub ? b2i_PublicKey(&p, len - 1) : b2i_PrivateKey(&p, len - 1);
    show_key("one short", got, k);
    EVP_PKEY_free(got);
    p = blob;
    got = ispub ? b2i_PublicKey(&p, 15) : b2i_PrivateKey(&p, 15);
    show_key("15 octets", got, k);
    EVP_PKEY_free(got);
    /* A longer buffer is fine. */
    again = OPENSSL_zalloc(len + 10);
    memcpy(again, blob, len);
    p = again;
    got = ispub ? b2i_PublicKey(&p, len + 10) : b2i_PrivateKey(&p, len + 10);
    show_key("longer", got, k);
    EVP_PKEY_free(got);
    OPENSSL_free(again);

    /* From a BIO, whole, short, and the other kind. */
    b = BIO_new_mem_buf(blob, (int)len);
    got = ispub ? b2i_PublicKey_bio(b) : b2i_PrivateKey_bio(b);
    show_key("bio", got, k);
    printf("  left %d\n", (int)BIO_pending(b));
    EVP_PKEY_free(got);
    BIO_free(b);
    b = BIO_new_mem_buf(blob, (int)len - 1);
    got = ispub ? b2i_PublicKey_bio(b) : b2i_PrivateKey_bio(b);
    show_key("bio one short", got, k);
    EVP_PKEY_free(got);
    BIO_free(b);
    b = BIO_new_mem_buf(blob, 10);
    got = ispub ? b2i_PublicKey_bio(b) : b2i_PrivateKey_bio(b);
    show_key("bio 10 octets", got, k);
    EVP_PKEY_free(got);
    BIO_free(b);
    b = BIO_new_mem_buf(blob, (int)len);
    got = ispub ? b2i_PrivateKey_bio(b) : b2i_PublicKey_bio(b);
    show_key("bio other kind", got, k);
    EVP_PKEY_free(got);
    BIO_free(b);

    /* Through the decoders, by input type, any input, and the other selection. */
    {
        static const char *inputs[] = { "MSBLOB", NULL };
        int i;

        for (i = 0; i < 3; i++) {
            OSSL_DECODER_CTX *dctx;
            EVP_PKEY *dk = NULL;
            int sel = i == 2 ? (ispub ? EVP_PKEY_KEYPAIR : OSSL_KEYMGMT_SELECT_PUBLIC_KEY) : 0;
            const unsigned char *dp = blob;
            size_t dl = len;
            int r;

            dctx = OSSL_DECODER_CTX_new_for_pkey(&dk, i == 1 ? NULL : inputs[0], NULL, NULL, sel,
                                                 NULL, NULL);
            r = OSSL_DECODER_from_data(dctx, &dp, &dl);
            printf("  decoder %s, selection %d: %d, left %zu\n", i == 1 ? "any" : "MSBLOB", sel, r,
                   dl);
            if (dk != NULL)
                show_key("decoded", dk, k);
            else
                ERR_clear_error();
            EVP_PKEY_free(dk);
            OSSL_DECODER_CTX_free(dctx);
        }
    }

    /* Through the encoder. */
    {
        int sel = ispub ? OSSL_KEYMGMT_SELECT_PUBLIC_KEY : EVP_PKEY_KEYPAIR;
        OSSL_ENCODER_CTX *ectx = OSSL_ENCODER_CTX_new_for_pkey(k, sel, "MSBLOB", NULL, NULL);
        unsigned char *data = NULL;
        size_t dlen = 0;

        printf("  encoders: %d\n", OSSL_ENCODER_CTX_get_num_encoders(ectx));
        check(OSSL_ENCODER_to_data(ectx, &data, &dlen) == 1, "encoded");
        check(dlen == (size_t)len && memcmp(data, blob, len) == 0, "the same as written");
        OPENSSL_free(data);
        OSSL_ENCODER_CTX_free(ectx);
    }
    OPENSSL_free(blob);
}

