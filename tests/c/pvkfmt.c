/*
 * Conformance test for Microsoft's key blobs and PVK files (b2i_PrivateKey(3) and the other
 * b2i_ and i2b_ functions, b2i_PVK_bio and i2b_PVK_bio with their _ex forms) and the MSBLOB
 * and PVK decoders and encoders, in TAP format: RSA and DSA keys written as blobs and
 * unencrypted PVKs (printed as their length and hash), read back to the same keys, and the
 * errors of truncated, mismatched, and malformed input and of keys a blob can't hold.
 *
 * An encrypted PVK needs RC4 and PVKKDF, the legacy provider's (step 9.1), so encrypting and
 * decrypting one fails here on both libraries, after asking for the passphrase.
 *
 * Built once against the vendored headers, then run against the reference OpenSSL and against
 * rustyssl: it must pass on both with the same output (TEST_PLAN.md, layer L4).
 */
