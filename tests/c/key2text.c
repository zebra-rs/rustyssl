static int failures = 0;
static int number = 0;

static void check(int ok, const char *what)
{
    number++;
    if (!ok)
        failures++;
    printf("%s %d - %s\n", ok ? "ok" : "not ok", number, what);
}

static void errors(void)
{
    unsigned long e;
    const char *data;
    int flags;

    printf("  errors:");
    while ((e = ERR_get_error_all(NULL, NULL, NULL, &data, &flags)) != 0) {
        printf(" %d/%d", ERR_GET_LIB(e), ERR_GET_REASON(e));
        if ((flags & ERR_TXT_STRING) != 0 && data != NULL && *data != '\0')
            printf(" [%s]", data);
    }
    printf("\n");
}

/* What was written, line by line, marked so the TAP stream stays readable. */
static void dump(BIO *b)
{
    char *data = NULL;
    long n = BIO_get_mem_data(b, &data), i, start = 0;

    for (i = 0; i < n; i++) {
        if (data[i] == '\n') {
            printf("  | %.*s\n", (int)(i - start), data + start);
            start = i + 1;
        }
    }
    if (start < n)
        printf("  | %.*s (no newline)\n", (int)(n - start), data + start);
}

static unsigned char *der_of(const char *b64, int len)
{
    unsigned char *out = OPENSSL_malloc(strlen(b64));

    if (out != NULL && EVP_DecodeBlock(out, (const unsigned char *)b64, (int)strlen(b64)) < len) {
        OPENSSL_free(out);
        return NULL;
    }
    return out;
}

static EVP_PKEY *decode(const unsigned char *der, size_t len, const char *structure,
                        const char *keytype, int selection)
{
    EVP_PKEY *pkey = NULL;
    OSSL_DECODER_CTX *dctx = OSSL_DECODER_CTX_new_for_pkey(&pkey, "DER", structure, keytype,
                                                           selection, NULL, NULL);

    if (dctx == NULL || !OSSL_DECODER_from_data(dctx, &der, &len)) {
        EVP_PKEY_free(pkey);
        pkey = NULL;
    }
    OSSL_DECODER_CTX_free(dctx);
    return pkey;
}

/* The three EVP_PKEY_print functions, at indentations 0 and 3. */
static void print_all(const char *name, EVP_PKEY *pkey)
{
    static const char *const fns[] = { "public", "private", "params" };
    int i, indent;

    for (i = 0; i < 3; i++) {
        for (indent = 0; indent <= 3; indent += 3) {
            BIO *b = BIO_new(BIO_s_mem());
            int r = i == 0   ? EVP_PKEY_print_public(b, pkey, indent, NULL)
                    : i == 1 ? EVP_PKEY_print_private(b, pkey, indent, NULL)
                             : EVP_PKEY_print_params(b, pkey, indent, NULL);

            printf("  %s print_%s indent %d: %d\n", name, fns[i], indent, r);
            dump(b);
            if (r <= 0)
                errors();
            BIO_free(b);
        }
    }
}

/* The TEXT encoders with selections the print functions don't use. */
static void text_selections(const char *name, EVP_PKEY *pkey)
{
    static const int sels[] = { OSSL_KEYMGMT_SELECT_PRIVATE_KEY, OSSL_KEYMGMT_SELECT_PUBLIC_KEY,
                                OSSL_KEYMGMT_SELECT_DOMAIN_PARAMETERS,
                                OSSL_KEYMGMT_SELECT_OTHER_PARAMETERS, OSSL_KEYMGMT_SELECT_KEYPAIR };
    size_t i;

    for (i = 0; i < sizeof(sels) / sizeof(sels[0]); i++) {
        OSSL_ENCODER_CTX *ctx = OSSL_ENCODER_CTX_new_for_pkey(pkey, sels[i], "TEXT", NULL, NULL);
        BIO *b = BIO_new(BIO_s_mem());
        int n = OSSL_ENCODER_CTX_get_num_encoders(ctx), r = OSSL_ENCODER_to_bio(ctx, b);

        printf("  %s TEXT selection 0x%x (%d encoders): %d\n", name, sels[i], n, r);
        dump(b);
        if (!r)
            errors();
        BIO_free(b);
        OSSL_ENCODER_CTX_free(ctx);
    }
}

static void print_fp(const char *name, EVP_PKEY *pkey)
{
    FILE *f = tmpfile();
    char buf[16384];
    size_t n;
    int r1, r2, r3;

    if (f == NULL)
        return;
    r1 = EVP_PKEY_print_public_fp(f, pkey, 2, NULL);
    r2 = EVP_PKEY_print_private_fp(f, pkey, 0, NULL);
    r3 = EVP_PKEY_print_params_fp(f, pkey, 1, NULL);
    fflush(f);
    rewind(f);
    n = fread(buf, 1, sizeof(buf) - 1, f);
    buf[n] = '\0';
    printf("  %s _fp: %d %d %d, %zu octets\n", name, r1, r2, r3, n);
    fclose(f);
    ERR_clear_error();
}

