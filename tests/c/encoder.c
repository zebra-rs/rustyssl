/* A traditional encrypted PEM of the key, its headers, and whether it decrypts to the key. */
static void encrypted(const char *label, EVP_PKEY *pkey, int how)
{
    OSSL_ENCODER_CTX *ctx = OSSL_ENCODER_CTX_new_for_pkey(pkey, EVP_PKEY_KEYPAIR, "PEM",
                                                          "type-specific", NULL);
    unsigned char *data = NULL;
    size_t len = 0;
    char what[100];
    int ok;

    check(OSSL_ENCODER_CTX_set_cipher(ctx, "AES-128-CBC", NULL), "set_cipher");
    switch (how) {
    case 0:
        ok = OSSL_ENCODER_CTX_set_passphrase(ctx, (const unsigned char *)"pass", 4);
        break;
    case 1:
        ok = OSSL_ENCODER_CTX_set_pem_password_cb(ctx, pem_cb, "pass");
        break;
    default:
        ok = OSSL_ENCODER_CTX_set_passphrase_cb(ctx, ossl_cb, "pass");
        break;
    }
    snprintf(what, sizeof(what), "%s: the passphrase set", label);
    check(ok, what);
    snprintf(what, sizeof(what), "%s: encoded", label);
    ok = OSSL_ENCODER_to_data(ctx, &data, &len);
    check(ok, what);
    if (ok) {
        BIO *b = BIO_new_mem_buf(data, (int)len);
        EVP_PKEY *back;
        char line[100];
        int i;

        for (i = 0; i < 3 && BIO_gets(b, line, sizeof(line)) > 0; i++) {
            if (i == 2)
                line[20] = '\0'; /* DEK-Info's cipher, not its random IV */
            printf("  %s", line);
            if (i == 2)
                printf("\n");
        }
        BIO_free(b);
        {
            const unsigned char *in = data;
            size_t inlen = len;
            OSSL_DECODER_CTX *dctx;

            back = NULL;
            dctx = OSSL_DECODER_CTX_new_for_pkey(&back, "PEM", NULL, NULL, 0, NULL, NULL);
            OSSL_DECODER_CTX_set_passphrase(dctx, (const unsigned char *)"pass", 4);
            OSSL_DECODER_from_data(dctx, &in, &inlen);
            OSSL_DECODER_CTX_free(dctx);
        }
        snprintf(what, sizeof(what), "%s: decrypts to the key", label);
        check(back != NULL && EVP_PKEY_eq(back, pkey) == 1, what);
        EVP_PKEY_free(back);
    } else {
        errors();
    }
    OPENSSL_free(data);
    OSSL_ENCODER_CTX_free(ctx);
}

