/* Every output type and structure of each selection of the key. */
static void matrix(const char *name, EVP_PKEY *pkey)
{
    size_t i, j;
    char what[200];

    snprintf(what, sizeof(what), "%s decoded", name);
    check(pkey != NULL, what);
    if (pkey == NULL) {
        errors();
        return;
    }
    for (j = 0; j < sizeof(selections) / sizeof(selections[0]); j++) {
        for (i = 0; i < sizeof(outputs) / sizeof(outputs[0]); i++) {
            OSSL_ENCODER_CTX *ctx = OSSL_ENCODER_CTX_new_for_pkey(pkey, selections[j].selection,
                                                                  outputs[i].type,
                                                                  outputs[i].structure, NULL);
            unsigned char *data = NULL;
            size_t len = 0;
            int n, ok;

            if (ctx == NULL) {
                printf("  %s %s %s/%s: no context\n", name, selections[j].name, outputs[i].type,
                       outputs[i].structure == NULL ? "-" : outputs[i].structure);
                errors();
                continue;
            }
            n = OSSL_ENCODER_CTX_get_num_encoders(ctx);
            ok = OSSL_ENCODER_to_data(ctx, &data, &len);
            snprintf(what, sizeof(what), "%s %s %s/%s (%d encoders)", name, selections[j].name,
                     outputs[i].type,
                     outputs[i].structure == NULL ? "-" : outputs[i].structure, n);
            if (ok) {
                show(what, data, len);
            } else {
                printf("  %s: fails\n", what);
                errors();
            }
            OPENSSL_free(data);
            OSSL_ENCODER_CTX_free(ctx);
        }
    }
}

