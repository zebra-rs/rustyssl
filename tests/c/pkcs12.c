    errors();
    printf("  PKCS12_get_attr %s, PKCS12_get_attr_gen %s\n", PKCS12_get_attr(bag, NID_ms_csp_name) ? "set" : "none",
           PKCS12_get_attr_gen(PKCS12_SAFEBAG_get0_attrs(bag), NID_localKeyID) ? "set" : "none");
