static BIO *mem(const char *s)
{
    return BIO_new_mem_buf(s, -1);
}

static X509 *cert(const char *pem)
{
    BIO *b = mem(pem);
    X509 *x = PEM_read_bio_X509(b, NULL, NULL, NULL);

    BIO_free(b);
    return x;
}

static EVP_PKEY *key(const char *pem)
{
    BIO *b = mem(pem);
    EVP_PKEY *k = PEM_read_bio_PrivateKey(b, NULL, NULL, NULL);

    BIO_free(b);
    return k;
}

static PKCS12 *load(const unsigned char *der, long len)
{
    const unsigned char *p = der;

    return d2i_PKCS12(NULL, &p, len);
}

static const char *oid(const ASN1_OBJECT *o)
{
    static char bufs[4][80];
    static int k;
    char *buf = bufs[k++ % 4];

    if (o == NULL)
        return "(none)";
    OBJ_obj2txt(buf, 80, o, 0);
    return buf;
}

static void hex(const char *label, const unsigned char *p, int n)
{
    int i;

    printf("  %s (%d):", label, n);
    for (i = 0; i < n; i++)
        printf("%s%02x", i % 32 == 0 ? "\n    " : "", p[i]);
    printf("\n");
}

/* The SHA-256 of an encoding. */
static void fingerprint(const char *label, const unsigned char *d, int n)
{
    unsigned char md[32];
    unsigned int mdlen = 0;

    EVP_Digest(d, (size_t)n, md, &mdlen, EVP_sha256(), NULL);
    printf("  %s: DER %d,", label, n);
    hex("sha256", md, (int)mdlen);
}

static void p12_fingerprint(const char *label, PKCS12 *p12)
{
    unsigned char *d = NULL;
    int n = i2d_PKCS12(p12, &d);

    fingerprint(label, d, n);
    OPENSSL_free(d);
}

static void name_of(const char *label, X509 *x)
{
    char buf[256];

    X509_NAME_oneline(X509_get_subject_name(x), buf, sizeof(buf));
    printf("  %s %s\n", label, buf);
}

static void show_mac(PKCS12 *p12)
{
    const ASN1_OCTET_STRING *mac = NULL, *salt = NULL;
    const X509_ALGOR *alg = NULL;
    const ASN1_INTEGER *iter = NULL;

    printf("  MAC present %d", PKCS12_mac_present(p12));
    PKCS12_get0_mac(&mac, &alg, &salt, &iter, p12);
    if (alg != NULL)
        printf(", %s, mac %d, salt %d, iter %ld", oid(alg->algorithm), ASN1_STRING_length(mac),
               ASN1_STRING_length(salt), iter == NULL ? 1 : ASN1_INTEGER_get(iter));
    printf("\n");
}

static void show_bag(PKCS12_SAFEBAG *bag, const char *pass)
{
    int nid = PKCS12_SAFEBAG_get_nid(bag);
    char *fname = PKCS12_get_friendlyname(bag);
    const ASN1_TYPE *lkid = PKCS12_SAFEBAG_get0_attr(bag, NID_localKeyID);
    const STACK_OF(X509_ATTRIBUTE) *attrs = PKCS12_SAFEBAG_get0_attrs(bag);
    int i;

    printf("    bag %s (%d), bag nid %d, bag type %s, name %s, key id %d, attributes %d:", oid(PKCS12_SAFEBAG_get0_type(bag)),
           nid, PKCS12_SAFEBAG_get_bag_nid(bag), oid(PKCS12_SAFEBAG_get0_bag_type(bag)), fname ? fname : "(none)",
           lkid ? ASN1_STRING_length(lkid->value.octet_string) : -1, sk_X509_ATTRIBUTE_num(attrs));
    for (i = 0; i < sk_X509_ATTRIBUTE_num(attrs); i++)
        printf(" %s", oid(X509_ATTRIBUTE_get0_object(sk_X509_ATTRIBUTE_value(attrs, i))));
    printf("\n");
    OPENSSL_free(fname);
    printf("      p8inf %s, pkcs8 %s, safes %s, bag obj %s\n", PKCS12_SAFEBAG_get0_p8inf(bag) ? "set" : "none",
           PKCS12_SAFEBAG_get0_pkcs8(bag) ? "set" : "none", PKCS12_SAFEBAG_get0_safes(bag) ? "set" : "none",
           PKCS12_SAFEBAG_get0_bag_obj(bag) ? "set" : "none");
    if (nid == NID_certBag) {
        X509 *x = PKCS12_SAFEBAG_get1_cert(bag), *y = PKCS12_SAFEBAG_get1_cert_ex(bag, NULL, NULL);

        name_of("      certificate", x);
        printf("      _ex the same %d, as a CRL %s\n", x != NULL && y != NULL && X509_cmp(x, y) == 0,
               PKCS12_SAFEBAG_get1_crl(bag) ? "set" : "none");
        X509_free(x);
        X509_free(y);
    } else if (nid == NID_crlBag) {
        X509_CRL *c = PKCS12_SAFEBAG_get1_crl(bag), *d = PKCS12_SAFEBAG_get1_crl_ex(bag, NULL, NULL);

        printf("      CRL %s, _ex %s, as a certificate %s\n", c ? "set" : "none", d ? "set" : "none",
               PKCS12_SAFEBAG_get1_cert(bag) ? "set" : "none");
        X509_CRL_free(c);
        X509_CRL_free(d);
    } else if (nid == NID_keyBag) {
        EVP_PKEY *k = EVP_PKCS82PKEY(PKCS12_SAFEBAG_get0_p8inf(bag));

        printf("      key %s\n", k ? OBJ_nid2sn(EVP_PKEY_get_base_id(k)) : "(none)");
        EVP_PKEY_free(k);
    } else if (nid == NID_pkcs8ShroudedKeyBag) {
        PKCS8_PRIV_KEY_INFO *p8 = PKCS12_decrypt_skey(bag, pass, -1);
        PKCS8_PRIV_KEY_INFO *p8b = PKCS12_decrypt_skey_ex(bag, pass, -1, NULL, NULL);
        EVP_PKEY *k = p8 ? EVP_PKCS82PKEY(p8) : NULL;

        printf("      shrouded key %s, _ex %s\n", k ? OBJ_nid2sn(EVP_PKEY_get_base_id(k)) : "(none)", p8b ? "set" : "none");
        EVP_PKEY_free(k);
        PKCS8_PRIV_KEY_INFO_free(p8);
        PKCS8_PRIV_KEY_INFO_free(p8b);
        p8 = PKCS12_decrypt_skey(bag, "wrong", -1);
        printf("      with the wrong password %s\n", p8 ? "set" : "none");
        ERR_clear_error();
    } else if (nid == NID_secretBag) {
        const ASN1_TYPE *t = PKCS12_SAFEBAG_get0_bag_obj(bag);

        printf("      secret type %d, %d octets\n", t ? t->type : -1, t ? ASN1_STRING_length(t->value.octet_string) : -1);
    }
}

static void show_bags(const STACK_OF(PKCS12_SAFEBAG) *bags, const char *pass)
{
    int i;

    printf("   bags %d\n", sk_PKCS12_SAFEBAG_num(bags));
    for (i = 0; i < sk_PKCS12_SAFEBAG_num(bags); i++)
        show_bag(sk_PKCS12_SAFEBAG_value(bags, i), pass);
}

static void show(PKCS12 *p12, const char *pass)
{
    STACK_OF(PKCS7) *safes = PKCS12_unpack_authsafes(p12);
    int i;

    show_mac(p12);
    printf("  contents %d\n", sk_PKCS7_num(safes));
    for (i = 0; i < sk_PKCS7_num(safes); i++) {
        PKCS7 *p7 = sk_PKCS7_value(safes, i);
        int nid = OBJ_obj2nid(p7->type);
        STACK_OF(PKCS12_SAFEBAG) *bags = nid == NID_pkcs7_data ? PKCS12_unpack_p7data(p7)
                                         : nid == NID_pkcs7_encrypted ? PKCS12_unpack_p7encdata(p7, pass, -1) : NULL;

        printf("  %d: %s\n", i, oid(p7->type));
        show_bags(bags, pass);
        sk_PKCS12_SAFEBAG_pop_free(bags, PKCS12_SAFEBAG_free);
    }
    sk_PKCS7_pop_free(safes, PKCS7_free);
}

/* PKCS12_parse, with what it found. */
static int parses(PKCS12 *p12, const char *pass, int want_ca)
{
    EVP_PKEY *pk = NULL;
    X509 *x = NULL;
    STACK_OF(X509) *ca = NULL;
    int r = PKCS12_parse(p12, pass, &pk, &x, want_ca ? &ca : NULL);
    int len = -1;
    unsigned char *alias = x ? X509_alias_get0(x, &len) : NULL;

    printf("  PKCS12_parse %d: key %s, cert %s, alias %.*s, others %d\n", r, pk ? OBJ_nid2sn(EVP_PKEY_get_base_id(pk)) : "none",
           x ? "set" : "none", alias ? len : 6, alias ? (const char *)alias : "(none)", sk_X509_num(ca));
    if (x != NULL)
        name_of("  certificate", x);
    EVP_PKEY_free(pk);
    X509_free(x);
    sk_X509_pop_free(ca, X509_free);
    return r;
}

static int print_bag_cb(PKCS12_SAFEBAG *bag, void *arg)
{
    int *calls = arg;

    (*calls)++;
    printf("  callback %d: %s\n", *calls, bag ? oid(PKCS12_SAFEBAG_get0_type(bag)) : "(none)");
    /* Drop the other certificates. */
    if (PKCS12_SAFEBAG_get_nid(bag) == NID_certBag) {
        char *name = PKCS12_get_friendlyname(bag);

        OPENSSL_free(name);
        if (name == NULL)
            return 0;
    }
    return 1;
}

static int fail_cb(PKCS12_SAFEBAG *bag, void *arg)
{
    (void)bag;
    (void)arg;
    return -1;
}

