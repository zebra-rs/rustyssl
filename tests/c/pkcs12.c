    show(p12, "pw");
    check(PKCS12_newpass(p12, "pw", "new") == 1 && parses(p12, "new", 1) == 1, "PKCS12_newpass of triple DES");
    PKCS12_free(p12);
    p12 = load(NOMAC_P12, sizeof(NOMAC_P12));
    check(PKCS12_newpass(p12, "pw", "new") == 1 && parses(p12, "new", 1) == 1, "PKCS12_newpass without a MAC");
    PKCS12_free(p12);
    r = PKCS12_newpass(NULL, "pw", "new");
    errors();
    check(r == 0, "PKCS12_newpass of NULL");
