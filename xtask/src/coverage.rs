//! `cargo xtask coverage [--list PREFIX...]`: how much of the ABI is implemented, per library
//! and per header. It writes `docs/coverage.md`, which CI checks is current. With `--list`, it
//! prints the status of every export whose name starts with one of the prefixes instead.
//!
//! An export is **implemented** once `rustssl-capi` defines it (so codegen emits no stub) and a
//! C conformance test in `tests/c/` calls it (AGENTS.md, "How to work"). A test's calls are the
//! undefined symbols of its compiled object. So a call through a header macro counts for the
//! function the macro expands to (`BIO_get_mem_data` is `BIO_ctrl`), and a call through an
//! inline wrapper counts for the function the wrapper calls (`sk_X509_num` calls
//! `OPENSSL_sk_num`). An export that's defined but that no test calls fails the command, since it
//! would ship without a conformance test.
//!
//! Each export is grouped under the first header that declares it, read from the line markers
//! in clang's preprocessed headers. That way, declarations generated by macros land in the
//! header that invokes the macro (`DECLARE_ASN1_FUNCTIONS(X509)` in `x509.h` declares
//! `X509_new`).

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::fmt::Write as _;
use std::fs;
use std::process::Command;

use crate::codegen::exports::{LIBRARIES, PRIVATE_PREFIX, parse_version_script};
use crate::codegen::headers::{Context, identifiers};
use crate::codegen::stubs::{CAPI_SRC, implemented_functions};
use crate::targets::{OPENSSL_SERIES, TARGETS, Target, host};
use crate::test_c::{CFLAGS, cc, select};
use crate::util::{Result, run_output, target_dir, workspace_root};

const REPORT: &str = "docs/coverage.md";
const USAGE: &str = "usage: cargo xtask coverage [--list PREFIX...]";

/// One exported function.
struct Export {
    name: String,
    library: &'static str,
    /// The header that declares it, relative to `include/` (`openssl/buffer.h`).
    header: String,
    /// Defined in rustssl-capi, so codegen emits no stub for it.
    defined: bool,
    /// The C conformance tests that call it.
    tests: BTreeSet<String>,
}

impl Export {
    fn implemented(&self) -> bool {
        self.defined && !self.tests.is_empty()
    }

    fn status(&self) -> &'static str {
        match (self.defined, self.tests.is_empty()) {
            (true, false) => "implemented",
            (true, true) => "untested",
            (false, _) => "stub",
        }
    }
}

pub fn run(args: &[String]) -> Result {
    let prefixes = match args.split_first() {
        None => None,
        Some((flag, prefixes)) if flag == "--list" && !prefixes.is_empty() => Some(prefixes),
        _ => return Err(USAGE.into()),
    };
    let root = workspace_root();
    let ctx = Context::new(&root, &target_dir(&root).join("xtask/coverage"))?;
    let exports = collect(&ctx)?;
    if let Some(prefixes) = prefixes {
        list(&exports, prefixes);
        return Ok(());
    }

    let untested: Vec<&str> = exports
        .iter()
        .filter(|e| e.defined && e.tests.is_empty())
        .map(|e| e.name.as_str())
        .collect();
    if !untested.is_empty() {
        return Err(format!(
            "rustssl-capi defines {} export(s) that no C conformance test in tests/c calls: {}",
            untested.len(),
            untested.join(", ")
        )
        .into());
    }
    fs::write(root.join(REPORT), render(&exports)?)?;
    for (library, total, implemented) in totals(&exports) {
        println!(
            "{library}: {implemented} of {total} exports implemented ({})",
            percent(implemented, total)
        );
    }
    println!("Wrote {REPORT}");
    Ok(())
}

/// Every export with its header, whether rustssl-capi defines it, and the tests that call it.
fn collect(ctx: &Context) -> Result<Vec<Export>> {
    // Every target exports the same functions with the same prototypes (codegen checks), and
    // a fixed target keeps the report the same on every host.
    let target = TARGETS.first().ok_or("no targets")?;
    let mut exports = Vec::new();
    for library in LIBRARIES {
        let path = ctx
            .abi
            .join("config")
            .join(target.configure)
            .join(format!("{library}.ld"));
        let nodes = parse_version_script(&fs::read_to_string(&path)?)
            .map_err(|e| format!("{}: {e}", path.display()))?;
        for name in nodes.into_iter().flat_map(|(_, names)| names) {
            exports.push(Export {
                name,
                library,
                header: String::new(),
                defined: false,
                tests: BTreeSet::new(),
            });
        }
    }

    let names: HashSet<&str> = exports.iter().map(|e| e.name.as_str()).collect();
    let headers = declaring_headers(ctx, target, &names)?;
    let defined = implemented_functions(&ctx.root.join(CAPI_SRC))?;
    let mut calls = test_calls(ctx)?;
    for export in &mut exports {
        export.header = headers
            .get(&export.name)
            .cloned()
            .ok_or_else(|| format!("no vendored header declares {}", export.name))?;
        export.defined = if export.library == "libssl" {
            defined.contains(&format!("{PRIVATE_PREFIX}{}", export.name))
        } else {
            defined.contains(&export.name)
        };
        export.tests = calls.remove(&export.name).unwrap_or_default();
    }
    exports.sort_by(|a, b| (a.library, &a.name).cmp(&(b.library, &b.name)));
    Ok(exports)
}

/// The header that first mentions each of `names` in the preprocessed headers. C requires a
/// declaration before any use, so the first mention is a declaration.
fn declaring_headers(
    ctx: &Context,
    target: &Target,
    names: &HashSet<&str>,
) -> Result<HashMap<String, String>> {
    let text = run_output(
        Command::new("clang")
            .args(ctx.clang_flags(target))
            .args(["-E", "-x", "c"])
            .arg(&ctx.wrapper),
    )?;
    Ok(first_mentions(
        &text,
        &format!("{}/", ctx.abi.join("include").display()),
        names,
    ))
}

/// For preprocessed `text`, the file (relative to `include`) where each of `names` first
/// appears. Only files under `include` count.
fn first_mentions(text: &str, include: &str, names: &HashSet<&str>) -> HashMap<String, String> {
    let mut file: Option<&str> = None;
    let mut found = HashMap::new();
    for line in text.lines() {
        // Line markers look like `# 12 "/path/to/file.h" 2`; other directives are pragmas.
        if let Some(marker) = line.strip_prefix("# ") {
            file = marker
                .split('"')
                .nth(1)
                .and_then(|path| path.strip_prefix(include));
            continue;
        }
        let Some(header) = file else {
            continue;
        };
        if line.starts_with('#') {
            continue;
        }
        for id in identifiers(line) {
            if names.contains(id) && !found.contains_key(id) {
                found.insert(id.to_owned(), header.to_owned());
            }
        }
    }
    found
}

/// For each function the C conformance tests call, the tests that call it: the undefined
/// symbols of each test compiled for the host.
fn test_calls(ctx: &Context) -> Result<HashMap<String, BTreeSet<String>>> {
    let (_, host) = host()?;
    let config = ctx.abi.join("config").join(host.configure);
    let mut calls: HashMap<String, BTreeSet<String>> = HashMap::new();
    for (name, source) in select(&ctx.root.join("tests/c"), &[])? {
        let object = ctx.work.join(format!("{name}.o"));
        run_output(
            cc().args(CFLAGS)
                .arg("-I")
                .arg(&config)
                .arg("-I")
                .arg(ctx.abi.join("include"))
                .arg("-c")
                .arg(&source)
                .arg("-o")
                .arg(&object),
        )?;
        for (defined, symbol) in crate::dist::symbols(&object, host)? {
            if !defined {
                calls.entry(symbol).or_default().insert(name.clone());
            }
        }
    }
    Ok(calls)
}

/// Per library: (library, exports, implemented).
fn totals(exports: &[Export]) -> Vec<(&'static str, usize, usize)> {
    LIBRARIES
        .iter()
        .map(|library| {
            let of: Vec<&Export> = exports.iter().filter(|e| e.library == *library).collect();
            let implemented = of.iter().filter(|e| e.implemented()).count();
            (*library, of.len(), implemented)
        })
        .collect()
}

/// `part / whole` as a percentage with one decimal, rounded to nearest.
fn percent(part: usize, whole: usize) -> String {
    if whole == 0 {
        return "-".to_owned();
    }
    let tenths = (part * 1000 + whole / 2) / whole;
    format!("{}.{}%", tenths / 10, tenths % 10)
}

fn render(exports: &[Export]) -> Result<String> {
    let mut out = format!(
        "# Export coverage\n\n\
         Generated by `cargo xtask coverage` from the OpenSSL {OPENSSL_SERIES} export lists. Don't \
         edit it by hand:\nCI fails if it's out of date.\n\n\
         An export is **implemented** once `rustssl-capi` defines it and a C conformance test in \
         `tests/c/`\ncalls it. Every other export is a generated stub that aborts \
         (AGENTS.md, security rule 10).\n\n\
         | Library | Exports | Implemented | Stubs | Coverage |\n|---|--:|--:|--:|--:|\n"
    );
    let totals = totals(exports);
    for (library, total, implemented) in &totals {
        writeln!(
            out,
            "| {library} | {total} | {implemented} | {} | {} |",
            total - implemented,
            percent(*implemented, *total)
        )?;
    }
    let total: usize = totals.iter().map(|(_, total, _)| total).sum();
    let implemented: usize = totals.iter().map(|(_, _, implemented)| implemented).sum();
    writeln!(
        out,
        "| **Total** | **{total}** | **{implemented}** | **{}** | **{}** |",
        total - implemented,
        percent(implemented, total)
    )?;

    out.push_str(
        "\n## By header\n\n\
         Each export is listed under the header that declares it. The `internal/` headers \
         declare the few\ninternal APIs that libcrypto exports (`DSO_*` and others).\n\n\
         | Header | Library | Exports | Implemented | Coverage |\n|---|---|--:|--:|--:|\n",
    );
    let mut by_header: BTreeMap<(&str, &str), (usize, usize)> = BTreeMap::new();
    for export in exports {
        let entry = by_header
            .entry((export.header.as_str(), export.library))
            .or_default();
        entry.0 += 1;
        entry.1 += usize::from(export.implemented());
    }
    for ((header, library), (total, implemented)) in &by_header {
        writeln!(
            out,
            "| `{header}` | {library} | {total} | {implemented} | {} |",
            percent(*implemented, *total)
        )?;
    }

    out.push_str(
        "\n## Implemented exports\n\n| Export | Library | Header | Called by |\n|---|---|---|---|\n",
    );
    for export in exports.iter().filter(|e| e.implemented()) {
        let tests: Vec<String> = export.tests.iter().map(|t| format!("`{t}`")).collect();
        writeln!(
            out,
            "| `{}` | {} | `{}` | {} |",
            export.name,
            export.library,
            export.header,
            tests.join(", ")
        )?;
    }
    Ok(out)
}

/// Prints the status of each export whose name starts with one of `prefixes`.
fn list(exports: &[Export], prefixes: &[String]) {
    let matching: Vec<&Export> = exports
        .iter()
        .filter(|e| prefixes.iter().any(|p| e.name.starts_with(p.as_str())))
        .collect();
    let width = matching.iter().map(|e| e.name.len()).max().unwrap_or(0);
    for export in &matching {
        let tests: Vec<&str> = export.tests.iter().map(String::as_str).collect();
        println!(
            "{:<11}  {:<width$}  {:<9}  {:<28}  {}",
            export.status(),
            export.name,
            export.library,
            export.header,
            tests.join(", ")
        );
    }
    let implemented = matching.iter().filter(|e| e.implemented()).count();
    println!(
        "{implemented} of {} matching exports implemented ({})",
        matching.len(),
        percent(implemented, matching.len())
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn percentages_round_to_one_decimal() {
        assert_eq!(percent(6, 6476), "0.1%");
        assert_eq!(percent(0, 603), "0.0%");
        assert_eq!(percent(1, 3), "33.3%");
        assert_eq!(percent(2, 3), "66.7%");
        assert_eq!(percent(5, 5), "100.0%");
        assert_eq!(percent(0, 0), "-");
    }

    #[test]
    fn the_first_header_that_mentions_a_name_declares_it() {
        let text = "# 1 \"/abi/include/openssl/stack.h\" 1\n\
                    int OPENSSL_sk_num(const OPENSSL_STACK *);\n\
                    # 1 \"/abi/include/openssl/x509.h\" 1\n\
                    #pragma X509_new\n\
                    static int sk_X509_num(void *sk) { return OPENSSL_sk_num(sk); }\n\
                    X509 *X509_new(void);\n\
                    # 1 \"/usr/include/stdio.h\" 1\n\
                    int X509_free(X509 *);\n\
                    # 7 \"/abi/include/internal/dso.h\" 2\n\
                    void X509_free(X509 *); DSO *DSO_new(void);\n";
        let names = HashSet::from(["OPENSSL_sk_num", "X509_new", "X509_free", "DSO_new"]);
        let found = first_mentions(text, "/abi/include/", &names);
        assert_eq!(found["OPENSSL_sk_num"], "openssl/stack.h");
        assert_eq!(found["X509_new"], "openssl/x509.h");
        assert_eq!(found["X509_free"], "internal/dso.h");
        assert_eq!(found["DSO_new"], "internal/dso.h");
        assert_eq!(found.len(), 4);
    }

    #[test]
    fn status_needs_a_definition_and_a_test() {
        let export = |defined, tests: &[&str]| Export {
            name: "BUF_MEM_new".to_owned(),
            library: "libcrypto",
            header: "openssl/buffer.h".to_owned(),
            defined,
            tests: tests.iter().map(|t| (*t).to_owned()).collect(),
        };
        assert_eq!(export(true, &["buf_mem"]).status(), "implemented");
        assert_eq!(export(true, &[]).status(), "untested");
        assert_eq!(export(false, &["buf_mem"]).status(), "stub");
        assert!(!export(false, &["buf_mem"]).implemented());
    }
}
