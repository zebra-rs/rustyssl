//! Generates OpenSSL's object table for `rustyssl-asn1`
//! (`crates/rustyssl-asn1/src/generated/objects.rs`): every NID with its short name, long name,
//! and DER-encoded OID, plus the signature-algorithm cross-reference from `obj_xref.txt`.
//!
//! The source is the `NID_x`/`SN_x`/`LN_x`/`OBJ_x` macros in `obj_mac.h`, which OpenSSL
//! generates from `objects.txt`, read the way OpenSSL's `obj_dat.pl` reads them to build its
//! own table (`obj_dat.h`). Its quirks are reproduced because they're observable:
//! - a missing short or long name is copied from the other, and an object with neither is
//!   named `"NULL"` (`NID_ac_auditEntity`);
//! - an OID is encoded only if its `OBJ_x` definition contains a comma. That leaves out the
//!   single-arc roots (`undef`, `iso`, `itu-t`, `joint-iso-itu-t`) and bare aliases such as
//!   `OBJ_ac_auditEntity`, which `obj_dat.pl` never expands;
//! - `NID_x` aliases of other NIDs (`NID_grasshopper_cbc`) aren't entries.
//!
//! NIDs and names come from the constants clang already evaluated; clang also expands each
//! `OBJ_x` arc list, so nested references need no reimplementation here.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::process::Command;

use super::abi::Constants;
use super::headers::{Context, identifiers, write_rust};
use crate::targets::{OPENSSL_SERIES, TARGETS};
use crate::util::Result;

struct Object {
    short_name: String,
    long_name: String,
    der: Vec<u8>,
}

pub fn generate(ctx: &Context, constants: &Constants) -> Result {
    let defined = obj_mac_macros(ctx)?;
    let mut nids: BTreeMap<String, i64> = BTreeMap::new();
    // Aliases like `#define NID_grasshopper_cbc NID_kuznyechik_cbc` aren't table entries:
    // obj_dat.pl only records NIDs written as numbers.
    let numeric = |name: &str| defined.get(name).is_some_and(|b| b.parse::<i64>().is_ok());
    for c in constants.ints.iter().filter(|c| numeric(&c.name)) {
        if let Some(name) = c.name.strip_prefix("NID_") {
            nids.insert(name.to_owned(), c.value);
        }
    }
    let strings: BTreeMap<&str, &[u8]> = constants
        .strings
        .iter()
        .filter(|(name, _)| defined.contains_key(name))
        .map(|(name, bytes)| (name.as_str(), bytes.as_slice()))
        .collect();
    let arcs = object_arcs(ctx, &nids)?;

    let mut objects: BTreeMap<i64, (String, Object)> = BTreeMap::new();
    for (name, &nid) in &nids {
        let text = |prefix: &str| -> Result<Option<String>> {
            match strings.get(format!("{prefix}{name}").as_str()) {
                Some(bytes) => Ok(Some(String::from_utf8(bytes.to_vec())?)),
                None => Ok(None),
            }
        };
        let (short_name, long_name) = match (text("SN_")?, text("LN_")?) {
            (Some(short), Some(long)) => (short, long),
            (Some(only), None) | (None, Some(only)) => (only.clone(), only),
            (None, None) => ("NULL".to_owned(), "NULL".to_owned()),
        };
        let has_arcs = defined
            .get(&format!("OBJ_{name}"))
            .is_some_and(|body| body.contains(','));
        let der = match arcs.get(name) {
            Some(arcs) if has_arcs => der_content(arcs).map_err(|e| format!("OBJ_{name}: {e}"))?,
            _ => Vec::new(),
        };
        let object = Object {
            short_name,
            long_name,
            der,
        };
        if let Some((other, _)) = objects.insert(nid, (name.clone(), object)) {
            return Err(format!("NID {nid} is both NID_{other} and NID_{name}").into());
        }
    }

    let xref = signature_algorithms(ctx, &nids)?;
    let path = ctx
        .root
        .join("crates/rustyssl-asn1/src/generated/objects.rs");
    write_rust(&ctx.root, &path, &render(&objects, &xref)?)?;
    write_rust(
        &ctx.root,
        &ctx.root.join("crates/rustyssl-asn1/src/generated/mod.rs"),
        "// Generated by `cargo xtask codegen`. Do not edit.\n\npub(crate) mod objects;\n",
    )?;
    println!(
        "objects: {} NIDs (highest {}), {} with an OID, {} signature algorithms",
        objects.len(),
        objects.keys().next_back().copied().unwrap_or_default(),
        objects.values().filter(|(_, o)| !o.der.is_empty()).count(),
        xref.len()
    );
    Ok(())
}

/// Expands every `OBJ_x` macro that has a matching `NID_x` into its arcs, using clang.
fn object_arcs(ctx: &Context, nids: &BTreeMap<String, i64>) -> Result<BTreeMap<String, Vec<u64>>> {
    let target = TARGETS.first().ok_or("no targets")?;
    let macros = ctx.object_like_macros(target)?;
    let names: Vec<&String> = nids
        .keys()
        .filter(|name| macros.contains_key(&format!("OBJ_{name}")))
        .collect();
    let mut source = format!("#include \"{}\"\n", ctx.wrapper.display());
    for name in &names {
        writeln!(source, "const long rustyssl_o_{name}[] = {{ OBJ_{name} }};")?;
    }
    let c = ctx.work.join("objects.c");
    let ir = ctx.work.join("objects.ll");
    fs::write(&c, source)?;
    let output = Command::new("clang")
        .args(ctx.clang_flags(target))
        .args(["-S", "-emit-llvm", "-Wno-everything", "-o"])
        .arg(&ir)
        .arg(&c)
        .output()
        .map_err(|e| format!("cannot run `clang`: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "clang could not expand the OBJ_ macros:\n{}",
            String::from_utf8_lossy(&output.stderr)
        )
        .into());
    }
    let mut arcs = BTreeMap::new();
    for line in fs::read_to_string(&ir)?.lines() {
        if let Some((name, definition)) = line
            .strip_prefix("@rustyssl_o_")
            .and_then(|rest| rest.split_once(" = "))
        {
            arcs.insert(name.to_owned(), ir_i64_array(definition)?);
        }
    }
    if arcs.len() != names.len() {
        return Err(format!("expanded {} of {} OBJ_ macros", arcs.len(), names.len()).into());
    }
    Ok(arcs)
}

/// The elements of an IR array such as `constant [3 x i64] [i64 1, i64 2, i64 840], align 16`
/// or `constant [1 x i64] zeroinitializer, align 8`.
fn ir_i64_array(definition: &str) -> Result<Vec<u64>> {
    let (_, rest) = definition
        .split_once("constant [")
        .ok_or_else(|| format!("unexpected IR: {definition}"))?;
    let (count, rest) = rest
        .split_once(" x i64] ")
        .ok_or_else(|| format!("unexpected IR: {definition}"))?;
    let count: usize = count.parse()?;
    if rest.starts_with("zeroinitializer") {
        return Ok(vec![0; count]);
    }
    let (list, _) = rest
        .strip_prefix('[')
        .and_then(|r| r.split_once(']'))
        .ok_or_else(|| format!("unexpected IR: {definition}"))?;
    let values = list
        .split(',')
        .map(|item| -> Result<u64> {
            let number = item
                .trim()
                .strip_prefix("i64 ")
                .ok_or_else(|| format!("unexpected IR element: {item}"))?;
            Ok(number.parse()?)
        })
        .collect::<Result<Vec<u64>>>()?;
    if values.len() != count {
        return Err(format!("IR array length mismatch: {definition}").into());
    }
    Ok(values)
}

/// The macros `obj_mac.h` defines, with their bodies as written; `obj_dat.pl` reads only that
/// file.
fn obj_mac_macros(ctx: &Context) -> Result<BTreeMap<String, String>> {
    let text = fs::read_to_string(ctx.abi.join("include/openssl/obj_mac.h"))?;
    let mut macros = BTreeMap::new();
    for line in text.lines() {
        let Some(definition) = line
            .trim_start()
            .strip_prefix('#')
            .and_then(|l| l.trim_start().strip_prefix("define "))
        else {
            continue;
        };
        if let Some(name) = identifiers(definition).next() {
            let body = definition.trim_start().trim_start_matches(name).trim();
            macros.insert(name.to_owned(), body.to_owned());
        }
    }
    Ok(macros)
}

/// DER content octets of an OBJECT IDENTIFIER of two or more arcs.
fn der_content(arcs: &[u64]) -> Result<Vec<u8>> {
    let [first, second, rest @ ..] = arcs else {
        return Err(format!("an OID needs at least two arcs: {arcs:?}").into());
    };
    let (first, second) = (*first, *second);
    if first > 2 || (first < 2 && second > 39) {
        return Err(format!("invalid leading arcs {first}.{second}").into());
    }
    let mut der = Vec::new();
    for arc in std::iter::once(first * 40 + second).chain(rest.iter().copied()) {
        let mut groups = vec![u8::try_from(arc & 0x7f)?];
        let mut rest = arc >> 7;
        while rest > 0 {
            groups.push(u8::try_from(rest & 0x7f)? | 0x80);
            rest >>= 7;
        }
        der.extend(groups.iter().rev());
    }
    Ok(der)
}

/// The `obj_xref.txt` rows as (signature, digest, public key) NIDs, with the signature name.
fn signature_algorithms(
    ctx: &Context,
    nids: &BTreeMap<String, i64>,
) -> Result<Vec<(String, [i64; 3])>> {
    let text = fs::read_to_string(ctx.abi.join("crypto/objects/obj_xref.txt"))?;
    let mut rows = Vec::new();
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or_default().trim();
        if line.is_empty() {
            continue;
        }
        let fields: Vec<&str> = line.split_whitespace().collect();
        let [signature, digest, pkey] = fields.as_slice() else {
            return Err(format!("obj_xref.txt: unexpected line: {line}").into());
        };
        let nid = |name: &str| -> Result<i64> {
            nids.get(name)
                .copied()
                .ok_or_else(|| format!("obj_xref.txt: no NID_{name}").into())
        };
        rows.push((
            (*signature).to_owned(),
            [nid(signature)?, nid(digest)?, nid(pkey)?],
        ));
    }
    Ok(rows)
}

fn render(
    objects: &BTreeMap<i64, (String, Object)>,
    xref: &[(String, [i64; 3])],
) -> Result<String> {
    let mut out = format!(
        "// Generated by `cargo xtask codegen` from the object macros in abi/openssl-{OPENSSL_SERIES} \
         (obj_mac.h,\n// which OpenSSL generates from objects.txt) and from \
         crypto/objects/obj_xref.txt. Do not edit.\n\n\
         use crate::objects::{{ObjectDef, SignatureAlgorithm}};\n\n\
         /// Every object, indexed by NID. `None` marks NIDs that aren't assigned.\n\
         pub(crate) static OBJECTS: &[Option<ObjectDef>] = &[\n"
    );
    let highest = objects.keys().next_back().copied().unwrap_or_default();
    for nid in 0..=highest {
        let Some((name, object)) = objects.get(&nid) else {
            out.push_str("    None,\n");
            continue;
        };
        let der: Vec<String> = object.der.iter().map(|b| format!("{b:#04x}")).collect();
        writeln!(
            out,
            "    Some(ObjectDef {{ nid: {nid}, short_name: {:?}, long_name: {:?}, der: &[{}] }}), // {name}",
            object.short_name,
            object.long_name,
            der.join(", ")
        )?;
    }
    out.push_str(
        "];\n\n/// Signature algorithms with their digest and public-key algorithms.\n\
         pub(crate) static SIGNATURE_ALGORITHMS: &[SignatureAlgorithm] = &[\n",
    );
    for (name, [signature, digest, pkey]) in xref {
        writeln!(
            out,
            "    SignatureAlgorithm {{ signature: {signature}, digest: {digest}, pkey: {pkey} }}, // {name}"
        )?;
    }
    out.push_str("];\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn der_encodes_arcs() {
        // 2.16.840.1.101.3.4.2.1 (SHA-256)
        let sha256 = der_content(&[2, 16, 840, 1, 101, 3, 4, 2, 1]).unwrap();
        assert_eq!(
            sha256,
            [0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x01]
        );
        // 1.2.840.113549 (RSADSI): 113549 needs three base-128 groups.
        assert_eq!(
            der_content(&[1, 2, 840, 113549]).unwrap(),
            [0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d]
        );
        // 2.999: the first two arcs combine to 1079, which needs two groups.
        assert_eq!(der_content(&[2, 999]).unwrap(), [0x88, 0x37]);
        assert!(der_content(&[0]).is_err());
        assert!(der_content(&[1, 40]).is_err());
        assert!(der_content(&[3, 1]).is_err());
        assert!(der_content(&[1]).is_err());
    }

    #[test]
    fn parses_ir_arrays() {
        let full = "dso_local constant [3 x i64] [i64 1, i64 2, i64 840], align 16";
        assert_eq!(ir_i64_array(full).unwrap(), [1, 2, 840]);
        let zero = "dso_local constant [1 x i64] zeroinitializer, align 8";
        assert_eq!(ir_i64_array(zero).unwrap(), [0]);
        assert!(ir_i64_array("constant [2 x i64] [i64 1], align 8").is_err());
    }
}
