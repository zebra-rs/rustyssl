//! The verification errors' text (`X509_verify_cert_error_string`) from OpenSSL's
//! `crypto/x509/x509_txt.c`: each `case X509_V_ERR_*:` (or `X509_V_OK`) label with the string
//! its `return` gives, and the default's
//! (`crates/rustyssl-capi/src/generated/verify_strings.rs`).

use std::fmt::Write as _;
use std::fs;

use super::abi::Constants;
use super::headers::{Context, write_rust};
use crate::util::Result;

pub fn generate(ctx: &Context, constants: &Constants) -> Result {
    let source = fs::read_to_string(ctx.abi.join("crypto/x509/x509_txt.c"))?;
    let mut entries: Vec<(String, i64, String)> = Vec::new();
    let mut labels: Vec<String> = Vec::new();
    let mut default = None;
    let mut in_default = false;
    for line in source.lines().map(str::trim) {
        if let Some(rest) = line.strip_prefix("case ") {
            let label = rest.trim_end_matches(':').trim();
            labels.push(label.to_owned());
        } else if line == "default:" {
            in_default = true;
        } else if let Some(rest) = line.strip_prefix("return \"") {
            let text = rest
                .strip_suffix("\";")
                .ok_or_else(|| format!("x509_txt.c: unexpected return: {line}"))?;
            if in_default {
                default = Some(text.to_owned());
                in_default = false;
            }
            for label in labels.drain(..) {
                let value = constants
                    .ints
                    .iter()
                    .find(|c| c.name == label)
                    .map(|c| c.value)
                    .ok_or_else(|| format!("x509_txt.c: {label} isn't a header constant"))?;
                entries.push((label, value, text.to_owned()));
            }
        }
    }
    let default = default.ok_or("x509_txt.c: no default string")?;
    if entries.is_empty() || !labels.is_empty() {
        return Err("x509_txt.c: no strings, or a label without one".into());
    }
    let mut out = String::from(
        "// Generated by `cargo xtask codegen` from OpenSSL's crypto/x509/x509_txt.c.\n\
         // Do not edit.\n\n\
         use core::ffi::{CStr, c_int};\n\n\
         /// Each verification error and its text, in `x509_txt.c`'s order.\n\
         pub(crate) static VERIFY_STRINGS: &[(c_int, &CStr)] = &[\n",
    );
    for (label, value, text) in &entries {
        writeln!(out, "    ({value}, c\"{text}\"), // {label}")?;
    }
    out.push_str("];\n\n/// The text of any other error.\n");
    writeln!(out, "pub(crate) const UNKNOWN: &CStr = c\"{default}\";")?;
    let path = ctx
        .root
        .join("crates/rustyssl-capi/src/generated/verify_strings.rs");
    write_rust(&ctx.root, &path, &out)?;
    println!("verify strings: {}", entries.len());
    Ok(())
}
