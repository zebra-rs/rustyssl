//! Generates the reason-string table for the error queue
//! (`crates/rustssl-capi/src/generated/err_reasons.rs`).
//!
//! Three vendored sources are combined and checked against each other:
//! - `crypto/err/openssl.txt` lists every reason with its code;
//! - the headers define the codes as macros, which clang evaluated;
//! - the C string tables (`*_err.c`) hold the text OpenSSL prints at run time. A few strings
//!   were edited there without updating `openssl.txt`, so the C text wins, and each
//!   difference is reported on every run.
//!
//! Entries refer to library and reason codes by their `rustssl-abi` names, so they can't
//! drift from the headers. Reasons of internal libraries (SM2, the property parser) have no
//! header constant; their codes come from `openssl.txt` alone.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use super::abi::{Constants, c_literal};
use super::headers::{Context, identifiers, write_rust};
use crate::targets::OPENSSL_SERIES;
use crate::util::Result;

/// Reasons whose code in `openssl.txt` disagrees with the header upstream. The header is the
/// ABI applications compare against, and OpenSSL's own string table (`bio_err.c`) uses the
/// header's macro, so the header's value wins. Codegen fails if one of these is fixed upstream
/// or a new disagreement appears.
const KNOWN_MISMATCHES: &[&str] = &[
    // openssl.txt says 114; bioerr.h says 151.
    "BIO_R_PEER_ADDR_NOT_AVAILABLE",
];

struct Reason {
    library: String,
    name: String,
    text: String,
    library_code: i64,
    code: i64,
    /// Defined only in an internal header, so the code is written as a number.
    internal: bool,
}

pub fn generate(ctx: &Context, constants: &Constants) -> Result {
    let values: HashMap<&str, i64> = constants
        .ints
        .iter()
        .map(|c| (c.name.as_str(), c.value))
        .collect();
    let mut compiled = compiled_reasons(&ctx.abi)?;
    let text = fs::read_to_string(ctx.abi.join("crypto/err/openssl.txt"))?;
    let mut reasons = Vec::new();
    for (name, code, listed_text) in parse(&text)? {
        let (prefix, _) = name
            .split_once("_R_")
            .ok_or_else(|| format!("openssl.txt: {name} is not a reason code"))?;
        let library = format!("ERR_LIB_{prefix}");
        let library_code = *values
            .get(library.as_str())
            .ok_or_else(|| format!("openssl.txt: {name} has no {library} in the headers"))?;

        let (compiled_library, text) = compiled
            .remove(&name)
            .ok_or_else(|| format!("{name} is in openssl.txt but in no C string table"))?;
        if compiled_library != library {
            return Err(format!("{name} belongs to {compiled_library} in the C table").into());
        }
        if text != listed_text {
            println!("  note: {name}: printing {text:?}, not openssl.txt's {listed_text:?}");
        }

        let known = KNOWN_MISMATCHES.contains(&name.as_str());
        let (code, internal) = match values.get(name.as_str()) {
            Some(&value) if value == code && !known => (code, false),
            Some(&value) if value != code && known => (value, false),
            Some(&value) if known => {
                return Err(format!(
                    "{name} is {value} in both openssl.txt and the headers now; remove it from \
                     KNOWN_MISMATCHES"
                )
                .into());
            }
            Some(&value) => {
                return Err(format!(
                    "openssl.txt says {name} is {code}, but the headers say {value}"
                )
                .into());
            }
            None => (code, true),
        };
        reasons.push(Reason {
            library,
            name,
            text,
            library_code,
            code,
            internal,
        });
    }
    if !compiled.is_empty() {
        let mut extra: Vec<&String> = compiled.keys().collect();
        extra.sort();
        return Err(format!("C string tables have reasons openssl.txt lacks: {extra:?}").into());
    }
    reasons.sort_by_key(|r| (r.library_code, r.code));
    if let Some(pair) = reasons
        .windows(2)
        .find(|pair| matches!(pair, [a, b] if (a.library_code, a.code) == (b.library_code, b.code)))
        && let [a, b] = pair
    {
        return Err(format!("{} and {} have the same code", a.name, b.name).into());
    }

    let mut out = format!(
        "// Generated by `cargo xtask codegen` from abi/openssl-{OPENSSL_SERIES}: reasons from \
         crypto/err/openssl.txt,\n// texts from the C string tables (*_err.c). Do not edit.\n\n\
         use core::ffi::{{CStr, c_int}};\n\nuse rustssl_abi::*;\n\n\
         /// Reason strings as (library, reason, text), sorted by library and then reason.\n\
         pub(crate) static REASON_STRINGS: &[(c_int, c_int, &CStr)] = &[\n"
    );
    for r in &reasons {
        let text = c_literal(r.text.as_bytes());
        if r.internal {
            let (library, code, name) = (&r.library, r.code, &r.name);
            writeln!(
                out,
                "    ({library}, {code}, c\"{text}\"), // {name} (internal)"
            )?;
        } else {
            writeln!(out, "    ({}, {}, c\"{text}\"),", r.library, r.name)?;
        }
    }
    out.push_str("];\n");
    let path = ctx
        .root
        .join("crates/rustssl-capi/src/generated/err_reasons.rs");
    write_rust(&ctx.root, &path, &out)?;
    let internal = reasons.iter().filter(|r| r.internal).count();
    println!(
        "errors: {} reason strings ({internal} internal)",
        reasons.len()
    );
    Ok(())
}

/// Parses `NAME:code:text` lines. A line ending in `\` continues on the next line, whose
/// leading whitespace is dropped.
fn parse(text: &str) -> Result<Vec<(String, i64, String)>> {
    let mut logical = Vec::new();
    let mut pending = String::new();
    for line in text.lines() {
        let line = if pending.is_empty() {
            line
        } else {
            line.trim_start()
        };
        if let Some(head) = line.strip_suffix('\\') {
            pending.push_str(head);
            continue;
        }
        pending.push_str(line);
        logical.push(std::mem::take(&mut pending));
    }
    if !pending.is_empty() {
        return Err("openssl.txt ends with a continuation".into());
    }
    let mut entries = Vec::new();
    for line in logical {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut fields = line.splitn(3, ':');
        let (Some(name), Some(code), Some(reason)) = (fields.next(), fields.next(), fields.next())
        else {
            return Err(format!("openssl.txt: unexpected line: {line}").into());
        };
        entries.push((name.to_owned(), code.parse()?, reason.to_owned()));
    }
    Ok(entries)
}

/// Every reason in the vendored C string tables, mapped to its library macro and text.
fn compiled_reasons(abi: &Path) -> Result<HashMap<String, (String, String)>> {
    let mut reasons = HashMap::new();
    let mut dirs: Vec<PathBuf> = ["crypto", "ssl", "providers"]
        .iter()
        .map(|d| abi.join(d))
        .filter(|d| d.is_dir())
        .collect();
    while let Some(dir) = dirs.pop() {
        for entry in fs::read_dir(&dir)? {
            let path = entry?.path();
            if path.is_dir() {
                dirs.push(path);
            } else if path.extension().is_some_and(|e| e == "c") {
                let text = fs::read_to_string(&path)?;
                for (library, name, string) in
                    table_entries(&text).map_err(|e| format!("{}: {e}", path.display()))?
                {
                    // `err.c` names libraries with reason 0; those aren't reasons.
                    if name.contains("_R_") {
                        reasons.insert(name, (library, string));
                    }
                }
            }
        }
    }
    Ok(reasons)
}

/// The `{ ERR_PACK(ERR_LIB_x, 0, reason), "text" }` entries of a C string table, as
/// (library macro, reason macro, text).
fn table_entries(c: &str) -> Result<Vec<(String, String, String)>> {
    let mut entries = Vec::new();
    for piece in c.split("ERR_PACK(").skip(1) {
        let Some((arguments, rest)) = piece.split_once(')') else {
            continue;
        };
        let parts: Vec<&str> = arguments.split(',').map(str::trim).collect();
        let [library, "0", reason] = parts.as_slice() else {
            continue;
        };
        if !library.starts_with("ERR_LIB_") {
            continue;
        }
        let rest = rest
            .trim_start()
            .strip_prefix(',')
            .unwrap_or(rest)
            .trim_start();
        let text = string_literals(rest)?;
        let name = identifiers(reason).next().unwrap_or(reason);
        entries.push(((*library).to_owned(), name.to_owned(), text));
    }
    Ok(entries)
}

/// Reads one or more adjacent C string literals from the start of `text` and concatenates
/// them.
fn string_literals(mut text: &str) -> Result<String> {
    let mut out = String::new();
    let mut found = false;
    while let Some(body) = text.strip_prefix('"') {
        let mut chars = body.char_indices();
        let mut end = None;
        while let Some((i, c)) = chars.next() {
            match c {
                '"' => {
                    end = Some(i);
                    break;
                }
                '\\' => match chars.next() {
                    Some((_, 'n')) => out.push('\n'),
                    Some((_, 't')) => out.push('\t'),
                    Some((_, e @ ('\\' | '"' | '\''))) => out.push(e),
                    other => {
                        return Err(format!("unsupported escape {other:?} in a C string").into());
                    }
                },
                c => out.push(c),
            }
        }
        let end = end.ok_or("unterminated C string")?;
        text = body.get(end + 1..).unwrap_or_default().trim_start();
        found = true;
    }
    if found {
        Ok(out)
    } else {
        Err(format!(
            "expected a string literal at: {}",
            text.get(..40).unwrap_or(text)
        )
        .into())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_entries_and_continuations() {
        let text = "# comment\n#Reason codes\nASN1_R_ADDING_OBJECT:171:adding object\n\
                    BIO_R_NO_ACCEPT_ADDR_OR_SERVICE_SPECIFIED:143:\\\n\tno accept addr or service \
                    specified\n\nSSL_R_X:1:a: colon\n";
        let entries = parse(text).unwrap();
        assert_eq!(entries.len(), 3);
        assert_eq!(
            entries[0],
            ("ASN1_R_ADDING_OBJECT".into(), 171, "adding object".into())
        );
        assert_eq!(entries[1].2, "no accept addr or service specified");
        assert_eq!(entries[2].2, "a: colon");
        assert!(parse("A_R_B:1:x\\\n").is_err());
        assert!(parse("A_R_B:notanumber:x\n").is_err());
    }

    #[test]
    fn reads_c_string_tables() {
        let c = r#"static const ERR_STRING_DATA BIO_str_reasons[] = {
    { ERR_PACK(ERR_LIB_BIO, 0, BIO_R_NON_FATAL), "non-fatal or transient error" },
    {ERR_PACK(ERR_LIB_ASN1, 0, ASN1_R_X),
    "split \"quoted\" "
        "text"},
    { ERR_PACK(ERR_LIB_SYS, 0, 0), "system library" },
    {0, NULL}
};"#;
        let entries = table_entries(c).unwrap();
        assert_eq!(entries.len(), 3);
        assert_eq!(
            entries[0],
            (
                "ERR_LIB_BIO".into(),
                "BIO_R_NON_FATAL".into(),
                "non-fatal or transient error".into()
            )
        );
        assert_eq!(entries[1].2, "split \"quoted\" text");
        assert_eq!(entries[2].1, "0");
        assert!(string_literals("\"unterminated").is_err());
        assert!(string_literals("NULL }").is_err());
    }
}
