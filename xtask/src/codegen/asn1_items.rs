//! Generates OpenSSL's table of built-in ASN.1 items (`asn1_item_list`, which `ASN1_ITEM_get`
//! indexes and `ASN1_ITEM_lookup` searches by name) for `rustyssl-capi`
//! (`crates/rustyssl-capi/src/generated/asn1_item_list.rs`) from the vendored
//! `crypto/asn1/asn1_item_list.h`.
//!
//! The list's `#ifndef OPENSSL_NO_*` guards are resolved by clang with each target's
//! `configuration.h`; every target must give the same list. Each `ASN1_ITEM_ref(NAME)` becomes
//! a reference to rustyssl's `NAME_it`, whose module codegen finds as it does for the
//! signature checks, so the table can only name items rustyssl defines.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::process::Command;

use super::headers::{Context, write_rust};
use super::stubs::{CAPI_SRC, implemented_paths};
use crate::targets::TARGETS;
use crate::util::{Result, run_output};

const LIST: &str = "crypto/asn1/asn1_item_list.h";

pub fn generate(ctx: &Context) -> Result {
    let source = fs::read_to_string(ctx.abi.join(LIST))?;
    let mut agreed: Option<Vec<String>> = None;
    for target in TARGETS {
        let config = ctx
            .abi
            .join("config")
            .join(target.configure)
            .join("openssl/configuration.h");
        let items = items(&preprocess(ctx, &source, &config.to_string_lossy())?)?;
        match &agreed {
            Some(first) if *first != items => {
                return Err(format!(
                    "{} gives a different asn1_item_list from the other targets",
                    target.configure
                )
                .into());
            }
            _ => agreed = Some(items),
        }
    }
    let items = agreed.ok_or("no targets")?;
    let paths = implemented_paths(&ctx.root.join(CAPI_SRC))?;
    write_rust(
        &ctx.root,
        &ctx.root.join(CAPI_SRC).join("generated/asn1_item_list.rs"),
        &render(&items, &paths)?,
    )?;
    println!("asn1_item_list: {} items", items.len());
    Ok(())
}

/// The list's file preprocessed with `configuration.h` included first, its `#include` lines
/// dropped (it has none of its own today).
fn preprocess(ctx: &Context, source: &str, config: &str) -> Result<String> {
    let stripped: String = source
        .lines()
        .filter(|l| !l.trim_start().starts_with("#include"))
        .map(|l| format!("{l}\n"))
        .collect();
    let input = ctx.work.join("asn1_item_list.h");
    fs::write(&input, stripped)?;
    run_output(
        Command::new("clang")
            .args(["-E", "-P", "-x", "c", "-include", config])
            .arg(&input),
    )
}

/// The `ASN1_ITEM_ref(NAME)` entries of the preprocessed list, in order, as `NAME_it`.
fn items(text: &str) -> Result<Vec<String>> {
    const REF: &str = "ASN1_ITEM_ref(";
    let mut out = Vec::new();
    let mut rest = text;
    while let Some(at) = rest.find(REF) {
        let after = rest.get(at + REF.len()..).unwrap_or_default();
        let (name, tail) = after
            .split_once(')')
            .ok_or("asn1_item_list.h: an unterminated ASN1_ITEM_ref")?;
        let name = name.trim();
        if name.is_empty() || !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            return Err(format!("asn1_item_list.h: unexpected item {name:?}").into());
        }
        out.push(format!("{name}_it"));
        rest = tail;
    }
    if out.is_empty() {
        return Err("asn1_item_list.h lists no items".into());
    }
    Ok(out)
}

fn render(items: &[String], paths: &BTreeMap<String, String>) -> Result<String> {
    let mut s = String::from(
        "// Generated by `cargo xtask codegen` from the vendored crypto/asn1/asn1_item_list.h.\n\
         // Do not edit.\n\n\
         use rustyssl_abi::ASN1_ITEM;\n\n\
         /// OpenSSL's built-in items, in its order (`ASN1_ITEM_get`, `ASN1_ITEM_lookup`).\n\
         pub(crate) static ASN1_ITEM_LIST: &[unsafe extern \"C\" fn() -> *const ASN1_ITEM] = &[\n",
    );
    let mut missing = Vec::new();
    for name in items {
        match paths.get(name) {
            Some(module) => writeln!(s, "    {module}::{name},")?,
            None => missing.push(name.as_str()),
        }
    }
    if !missing.is_empty() {
        return Err(format!(
            "asn1_item_list names items rustyssl-capi doesn't define: {}",
            missing.join(", ")
        )
        .into());
    }
    s.push_str("];\n");
    Ok(s)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_item_references_in_order() {
        let text = "static const ASN1_ITEM_EXP *asn1_item_list[] = {\n    ASN1_ITEM_ref(ACCESS_DESCRIPTION),\n    ASN1_ITEM_ref( X509 ),\n};\n";
        assert_eq!(items(text).unwrap(), ["ACCESS_DESCRIPTION_it", "X509_it"]);
        assert!(items("nothing here").is_err());
        assert!(items("ASN1_ITEM_ref(a b)").is_err());
    }
}
