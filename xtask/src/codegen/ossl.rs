//! Generates `rustyssl-ossl`'s declarations of the public C API (ADR 0007, section 1): one
//! entry for every export of `libcrypto.num` and `libssl.num`, with the prototype the vendored
//! headers give it (the same prototypes `rustyssl-capi/src/generated/signatures.rs` asserts),
//! and the library it is resolved from at run time.
//!
//! Each entry expands, through `rustyssl-ossl`'s `import!` macro, to an `unsafe fn` of that
//! prototype which resolves the symbol once, when first called, and calls it. A C-variadic
//! function becomes a function returning the resolved pointer, which Rust can call with its
//! variable arguments; one taking a `va_list` is left out (stable Rust can't make one).
//!
//! Output: `crates/rustyssl-ossl/src/generated/ffi.rs`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::headers::{Context, identifiers, libc_types, write_rust};
use super::stubs::{Prototype, Prototypes};
use crate::targets::OPENSSL_SERIES;
use crate::util::Result;

const OUTPUT: &str = "crates/rustyssl-ossl/src/generated/ffi.rs";

pub fn generate(ctx: &Context, libraries: &Prototypes) -> Result {
    let mut body = String::new();
    let mut skipped = 0;
    for (library, functions) in libraries {
        let lib = match *library {
            "libcrypto" => "Crypto",
            "libssl" => "Ssl",
            other => return Err(format!("unknown library {other}").into()),
        };
        let (plain, variadic, n) = render_entries(functions);
        skipped += n;
        writeln!(body, "crate::import! {{\n    {lib};\n{plain}}}\n")?;
        writeln!(
            body,
            "crate::import_variadic! {{\n    {lib};\n{variadic}}}\n"
        )?;
    }
    let mut out = format!(
        "// Generated by `cargo xtask codegen` from the libcrypto and libssl export lists in\n\
         // abi/openssl-{OPENSSL_SERIES} and the prototypes in its headers. Do not edit.\n//\n\
         // Every export, resolved from its library when first called (ADR 0007, section 1). \
         The {skipped}\n// functions that take a `va_list` are left out.\n\n\
         #![allow(non_snake_case, clippy::too_many_arguments, clippy::missing_safety_doc)]\n\n"
    );
    let used: Vec<&str> = libc_types()
        .into_iter()
        .filter(|t| identifiers(&body).any(|id| id == *t))
        .collect();
    if !used.is_empty() {
        writeln!(out, "use libc::{{{}}};", used.join(", "))?;
    }
    out.push_str("use rustyssl_abi::*;\n\n");
    out.push_str(&body);
    write_rust(&ctx.root, &ctx.root.join(OUTPUT), &out)
}

/// The `import!` and `import_variadic!` entries for one library, and how many functions were
/// left out.
fn render_entries(functions: &BTreeMap<String, Prototype>) -> (String, String, usize) {
    let mut plain = String::new();
    let mut variadic = String::new();
    let mut skipped = 0;
    for (name, prototype) in functions {
        if prototype.params.iter().any(|p| p.contains("VaList")) {
            skipped += 1;
            continue;
        }
        let params: Vec<String> = prototype
            .params
            .iter()
            .enumerate()
            .map(|(i, ty)| format!("a{i}: {ty}"))
            .collect();
        let output = prototype
            .output
            .as_ref()
            .map_or_else(String::new, |ty| format!(" -> {ty}"));
        let out = if prototype.variadic {
            &mut variadic
        } else {
            &mut plain
        };
        let _ = writeln!(out, "    fn {name}({}){output};", params.join(", "));
    }
    (plain, variadic, skipped)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn entries_keep_the_prototype() {
        let mut f = BTreeMap::new();
        f.insert(
            "BIO_new".to_owned(),
            Prototype {
                params: vec!["* const BIO_METHOD".to_owned()],
                variadic: false,
                output: Some("* mut BIO".to_owned()),
            },
        );
        f.insert(
            "BIO_printf".to_owned(),
            Prototype {
                params: vec!["* mut BIO".to_owned(), "* const c_char".to_owned()],
                variadic: true,
                output: Some("c_int".to_owned()),
            },
        );
        f.insert(
            "BIO_vprintf".to_owned(),
            Prototype {
                params: vec!["* mut BIO".to_owned(), "core::ffi::VaList<'_>".to_owned()],
                variadic: false,
                output: Some("c_int".to_owned()),
            },
        );
        let (plain, variadic, skipped) = render_entries(&f);
        assert_eq!(skipped, 1);
        assert_eq!(
            plain,
            "    fn BIO_new(a0: * const BIO_METHOD) -> * mut BIO;\n"
        );
        assert_eq!(
            variadic,
            "    fn BIO_printf(a0: * mut BIO, a1: * const c_char) -> c_int;\n"
        );
    }
}
