//! `cargo xtask codegen`: regenerate everything derived from the vendored OpenSSL ABI in
//! `abi/`. Each generator documents its inputs and outputs.

mod abi;
mod asn1_items;
mod cli_options;
mod curves;
mod errors;
pub mod exports;
pub mod headers;
mod objects;
mod ossl;
pub mod profiles;
pub mod stubs;
mod verify_strings;

use std::process::Command;

use crate::targets::TARGETS;
use crate::util::{Result, run_output, target_dir, workspace_root};

pub fn run(args: &[String]) -> Result {
    if !args.is_empty() {
        return Err("usage: cargo xtask codegen".into());
    }
    headers::check_bindgen()?;
    let root = workspace_root();
    let ctx = headers::Context::new(&root, &target_dir(&root).join("xtask/codegen"))?;
    let constants = abi::generate(&ctx)?;
    let exports = exports::generate(&ctx)?;
    let prototypes = stubs::generate(&ctx, &exports)?;
    ossl::generate(&ctx, &prototypes)?;
    cli_options::generate(&ctx)?;
    asn1_items::generate(&ctx)?;
    errors::generate(&ctx, &constants)?;
    verify_strings::generate(&ctx, &constants)?;
    headers::write_rust(
        &ctx.root,
        &ctx.root.join("crates/rustyssl-capi/src/generated/mod.rs"),
        "// Generated by `cargo xtask codegen`. Do not edit.\n\n\
         pub(crate) mod asn1_item_list;\npub(crate) mod err_strings;\nmod libcrypto_stubs;\nmod libssl_stubs;\nmod signatures;\npub(crate) mod verify_strings;\n",
    )?;
    headers::write_rust(
        &ctx.root,
        &ctx.root.join("libs/libssl/src/generated/mod.rs"),
        "// Generated by `cargo xtask codegen`. Do not edit.\n\nmod libssl_forwarders;\n",
    )?;
    objects::generate(&ctx, &constants)?;
    curves::generate(&ctx, &constants)?;

    // Compiling for every target evaluates the layout assertions and type-checks the stubs.
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    for target in TARGETS {
        println!("Checking the generated code for {}...", target.rust);
        run_output(
            Command::new(&cargo)
                .args([
                    "check",
                    "--quiet",
                    "-p",
                    "rustyssl-capi",
                    "-p",
                    "rustyssl-asn1",
                    "-p",
                    "rustyssl-crypto",
                    "-p",
                    "rustyssl-libssl",
                    "-p",
                    "rustyssl-ossl",
                    "-p",
                    "rustyssl-cli",
                ])
                .args(["--target", target.rust])
                .current_dir(&ctx.root),
        )?;
    }
    Ok(())
}
